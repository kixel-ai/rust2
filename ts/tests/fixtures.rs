/// A caller of two functions of a type, through its module, as moq's TypeScript calls
/// the codec.
const SHAKE: &str = r#"import * as Decoder from "./coding/decode.Decoder.ts";
import * as rs from "./rs.ts";

export const run = (buf: Uint8Array) => Decoder.u8(Decoder.new(rs.byteSliceFrom(buf), { tag: "Quic" }));
"#;

/// Bun's and esbuild's tree-shaken bundles of [`SHAKE`] keep the functions it calls and
/// what they call, runtime included, and nothing else: no other function of the type,
/// though the caller imports its whole module, and none of the runtime's, though the
/// translation imports it whole. The bundles minify all but names and whitespace, which
/// would only rename and pack what is left.
fn shake(out: &Path) {
	let bundlers: [(&str, &[&str]); 2] = [
		("bun", &["build", "--target=browser", "--minify-syntax"]),
		(
			"esbuild",
			&["--bundle", "--format=esm", "--platform=browser", "--minify-syntax"],
		),
	];
	for (bundler, args) in bundlers {
		let output = Command::new(bundler)
			.args(args)
			.arg(out.join("shake.ts"))
			.output()
			.unwrap_or_else(|err| panic!("running {bundler}, which the dev shell provides: {err}"));
		let bundle = String::from_utf8_lossy(&output.stdout);
		assert!(
			output.status.success(),
			"bundling shake.ts with {bundler} failed:\n{}",
			String::from_utf8_lossy(&output.stderr)
		);
		// A bundler numbers a name another module also declares, `slice3`, so the digits
		// it adds go.
		let unnumbered = |name: &str| name.trim_end_matches(|c: char| c.is_ascii_digit()).to_string();
		let mut kept: Vec<String> = bundle
			.lines()
			.filter_map(|line| {
				["function ", "class ", "var ", "let ", "const "]
					.iter()
					.find_map(|k| line.strip_prefix(k))
			})
			.map(|decl| decl.split(['(', ' ', '{', '=']).next().unwrap())
			.map(unnumbered)
			.collect();
		kept.sort_unstable();
		let want = [
			// The runtime's.
			"ByteSlice",
			"Panic",
			"byteSliceFrom",
			"checked",
			"max",
			"panic",
			"saturate",
			"u32SaturatingAdd",
			"u32Sub",
			"usizeSaturatingAdd",
			"usizeSub",
			// The translation's, and the caller.
			"new_",
			"out$ref_slice_u8",
			"out$u8",
			"run",
			"short",
			"slice",
			"u8",
		];
		let mut want: Vec<String> = want.map(unnumbered).to_vec();
		want.sort_unstable();
		assert_eq!(
			kept, want,
			"{bundler}'s bundle keeps more than the caller reaches:\n{bundle}"
		);
	}
}

/// Adding a root changes only the output of what it reaches: everything else keeps its
/// text and order, though translation reaches it in another order.
#[test]
fn source_order() {
	let roots = r#"roots = ["harness::run", "bench::run"]"#;
	let base = rooted("codec", roots, "base", r#"roots = ["harness::run"]"#);
	// First, so that translation reaches what both share in another order.
	let added = r#"roots = ["bench::run", "harness::run"]"#;
	kept(&base, &rooted("codec", roots, "added", added), added);
}

/// Adding a root that reaches another instance of a generic function, or another trait's
/// impl of a method, renames nothing the old roots reach.
#[test]
fn stable_names() {
	let out = translated("names");
	snapshot("names", &out);
	typecheck(&out);
	let added = r#"roots = ["added", "run"]"#;
	let more = rooted("names", r#"roots = ["run"]"#, "added", added);
	kept(&sources(&out), &more, added);
}

/// Translate fixture `name` into `file` with its config's `roots` line replaced by `with`.
fn rooted(name: &str, roots: &str, file: &str, with: &str) -> Vec<(PathBuf, String)> {
	let config = std::fs::read_to_string(fixture(name).join("ts.toml")).unwrap();
	assert!(config.contains(roots), "{name}'s roots changed: update this test");
	let dir = scratch().join(name).join("order");
	std::fs::create_dir_all(&dir).unwrap();
	let path = dir.join(format!("{file}.toml"));
	std::fs::write(&path, config.replace(roots, with)).unwrap();
	let out = dir.join(file);
	let output = driver(name, &path, &["--out".as_ref(), out.as_ref()], "order");
	assert!(
		output.status.success(),
		"translating {name} with {with} failed:\n{}",
		String::from_utf8_lossy(&output.stderr)
	);
	sources(&out)
}

/// Check that every line of `base` stays, in order, in `more`, its translation once `added`.
fn kept(base: &[(PathBuf, String)], more: &[(PathBuf, String)], added: &str) {
	for (rel, text) in base {
		let more = more.iter().find(|(r, _)| r == rel).map(|(_, text)| text);
		let more = more.unwrap_or_else(|| panic!("{} is gone once {added}", rel.display()));
		let mut rest = lines(more).into_iter();
		for line in lines(text) {
			assert!(
				rest.any(|l| l == line),
				"{}: this line changed or moved once {added}:\n{line}",
				rel.display()
			);
		}
	}
}

/// A file's lines, with a line per imported name, so that importing one more name
/// changes no other line.
fn lines(text: &str) -> Vec<String> {
	let mut lines = Vec::new();
	for line in text.lines() {
		match line.strip_prefix("import { ").and_then(|l| l.split_once(" } from ")) {
			Some((names, from)) => {
				lines.extend(names.split(", ").map(|name| format!("import {{ {name} }} from {from}")))
			}
			None => lines.push(line.to_string()),
		}
	}
	lines
}

