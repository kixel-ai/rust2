//! Each fixture under `fixtures/` is translated, compared with its `expected/` snapshot,
//! type-checked with `tsc`, and, if it has a harness, run against its native build.
//!
//! `UPDATE_EXPECT=1 cargo test` rewrites the snapshots.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

const TARGET: &str = "wasm32-unknown-unknown";

/// The native side's profile, from `Cargo.toml`.
const PROFILE: &str = "differential";

fn manifest_dir() -> PathBuf {
	PathBuf::from(env!("CARGO_MANIFEST_DIR"))
}

fn scratch() -> PathBuf {
	PathBuf::from(env!("CARGO_TARGET_TMPDIR"))
}

fn cargo() -> Command {
	Command::new(std::env::var_os("CARGO").unwrap_or_else(|| "cargo".into()))
}

/// The manifest of the workspace the fixtures but `model` are members of.
fn workspace() -> PathBuf {
	manifest_dir().join("Cargo.toml")
}

fn fixture(name: &str) -> PathBuf {
	manifest_dir().join("fixtures").join(name)
}

/// Run the driver on a fixture with `config` and `args`, in its own build directory per
/// `build`.
fn driver(name: &str, config: &Path, args: &[&std::ffi::OsStr], build: &str) -> Output {
	driver_command(name, config, args, build)
		.output()
		.expect("running rust2-ts")
}

/// The command [`driver`] runs.
fn driver_command(name: &str, config: &Path, args: &[&std::ffi::OsStr], build: &str) -> Command {
	driver_at(&fixture(name).join("Cargo.toml"), config, args, build)
}

/// The command that runs the driver on the package of `manifest`.
fn driver_at(manifest: &Path, config: &Path, args: &[&std::ffi::OsStr], build: &str) -> Command {
	let mut command = Command::new(env!("CARGO_BIN_EXE_rust2-ts"));
	command
		.arg("--config")
		.arg(config)
		.arg("--manifest-path")
		.arg(manifest)
		.args(args)
		.env("CARGO_TARGET_DIR", scratch().join(build))
		.env("RUSTFLAGS", remap());
	command
}

/// The flags that name cargo's home `/cargo` in both builds, so the files of the registry's
/// crates, which a hook's locations name, are named alike on any host, and tokio's `sync`
/// module `tokio/channels` and bytes' `src` `bytes/source`, remaps of a directory within a
/// crate, which the locations of their panics must follow as native does.
fn remap() -> String {
	static FLAGS: std::sync::OnceLock<String> = std::sync::OnceLock::new();
	FLAGS.get_or_init(remap_flags).clone()
}

/// The flags [`remap`] gives, once the lockfile's crates are unpacked, so they don't
/// depend on what a build before unpacked.
fn remap_flags() -> String {
	let status = cargo()
		.args(["fetch", "--locked", "--manifest-path"])
		.arg(workspace())
		.status()
		.expect("running cargo");
	assert!(status.success(), "fetching the fixtures' crates failed");
	let home = match std::env::var_os("CARGO_HOME") {
		Some(home) => PathBuf::from(home),
		None => std::env::home_dir()
			.expect("a home directory, which holds cargo's")
			.join(".cargo"),
	};
	let lock = std::fs::read_to_string(manifest_dir().join("Cargo.lock")).unwrap();
	let version = |name: &str| {
		let (_, rest) = lock
			.split_once(&format!("name = \"{name}\"\nversion = \""))
			.unwrap_or_else(|| panic!("{name} in the lockfile"));
		format!("{name}-{}", &rest[..rest.find('"').unwrap()])
	};
	let dirs = [
		(version("tokio") + "/src/sync", "tokio/channels"),
		(version("bytes") + "/src", "bytes/source"),
	];
	// The later flag wins where both match.
	let mut flags = format!("--remap-path-prefix={}=/cargo", home.display());
	for index in std::fs::read_dir(home.join("registry/src")).into_iter().flatten() {
		let index = index.unwrap().path();
		for (dir, to) in &dirs {
			let dir = index.join(dir);
			if dir.is_dir() {
				flags += &format!(" --remap-path-prefix={}={to}", dir.display());
			}
		}
	}
	flags
}

/// Run the driver on a fixture, returning its output directory and what it printed.
fn translate(name: &str) -> (PathBuf, Output) {
	let out = scratch().join(name).join("out");
	let config = fixture(name).join("ts.toml");
	let output = driver(name, &config, &["--out".as_ref(), out.as_ref()], "build");
	(out, output)
}

fn translated(name: &str) -> PathBuf {
	let (out, output) = translate(name);
	assert!(
		output.status.success(),
		"translating {name} failed:\n{}",
		String::from_utf8_lossy(&output.stderr)
	);
	out
}

/// The generated TypeScript, by path relative to `dir`, without the runtime.
fn sources(dir: &Path) -> Vec<(PathBuf, String)> {
	let mut files = Vec::new();
	let mut stack = vec![dir.to_path_buf()];
	while let Some(next) = stack.pop() {
		let Ok(entries) = std::fs::read_dir(&next) else {
			continue;
		};
		for entry in entries {
			let path = entry.unwrap().path();
			if path.is_dir() {
				stack.push(path);
			} else if path.extension().is_some_and(|e| e == "ts") {
				let rel = path.strip_prefix(dir).unwrap().to_path_buf();
				let text = std::fs::read_to_string(&path).unwrap();
				// A hand-written caller copied in beside the output is no part of it.
				if rel != Path::new("rs.ts") && !rel.starts_with("rs") && text.starts_with("// Generated by rust2-ts.")
				{
					files.push((rel, text));
				}
			}
		}
	}
	files.sort();
	files
}

/// Compare the output with the fixture's `expected/` directory.
fn snapshot(name: &str, out: &Path) {
	let expected = fixture(name).join("expected");
	let got: Vec<_> = sources(out)
		.into_iter()
		.map(|(rel, text)| (rel, mask_type_ids(&text)))
		.collect();
	if std::env::var_os("UPDATE_EXPECT").is_some() {
		let _ = std::fs::remove_dir_all(&expected);
		for (rel, text) in &got {
			let path = expected.join(rel);
			std::fs::create_dir_all(path.parent().unwrap()).unwrap();
			std::fs::write(path, text).unwrap();
		}
		return;
	}
	let want = sources(&expected);
	let names = |files: &[(PathBuf, String)]| files.iter().map(|(p, _)| p.clone()).collect::<Vec<_>>();
	assert_eq!(
		names(&got),
		names(&want),
		"{name}: the generated files differ; rerun with UPDATE_EXPECT=1"
	);
	for ((rel, got), (_, want)) in got.iter().zip(&want) {
		assert!(
			got == want,
			"{name}: {} differs from its snapshot; rerun with UPDATE_EXPECT=1\n{}",
			rel.display(),
			diff(want, got)
		);
	}
}

/// `text` with each `TypeId`, a string literal of 32 hex digits, named by its first
/// appearance: cargo hashes the host's profile into a crate's `-C metadata`, and so into
/// the hash of every type it defines, which leaves only which ids are equal alike on
/// every host.
fn mask_type_ids(text: &str) -> String {
	let mut seen: Vec<&str> = Vec::new();
	let mut out = String::with_capacity(text.len());
	let mut rest = text;
	while let Some(at) = rest.find('"') {
		out.push_str(&rest[..=at]);
		rest = &rest[at + 1..];
		let hash = rest
			.get(..32)
			.filter(|hash| hash.bytes().all(|b| matches!(b, b'0'..=b'9' | b'a'..=b'f')))
			.filter(|_| rest[32..].starts_with('"'));
		if let Some(hash) = hash {
			let n = seen.iter().position(|seen| *seen == hash).unwrap_or_else(|| {
				seen.push(hash);
				seen.len() - 1
			});
			out.push_str(&format!("<TypeId {}>\"", n + 1));
			rest = &rest[33..];
		}
	}
	out.push_str(rest);
	out
}

/// The first lines where two texts differ.
fn diff(want: &str, got: &str) -> String {
	let (want, got): (Vec<&str>, Vec<&str>) = (want.lines().collect(), got.lines().collect());
	let start = want.iter().zip(&got).take_while(|(a, b)| a == b).count();
	let mut out = String::new();
	for line in want.iter().skip(start).take(8) {
		out.push_str(&format!("- {line}\n"));
	}
	for line in got.iter().skip(start).take(8) {
		out.push_str(&format!("+ {line}\n"));
	}
	out
}

/// Type-check the output as strict, erasable TypeScript, which Node runs as is.
fn typecheck(out: &Path) {
	// The runtime's settings: strict, and erasable so Node runs it as is.
	let runtime = manifest_dir().join("runtime").join("tsconfig.json");
	let config = format!(
		"{{ \"extends\": {:?}, \"files\": [], \"include\": [\"**/*.ts\"] }}\n",
		runtime.display().to_string()
	);
	std::fs::write(out.join("tsconfig.json"), config).unwrap();
	let output = Command::new("tsc")
		.arg("-p")
		.arg(out)
		.output()
		.expect("running tsc, which the dev shell provides");
	assert!(
		output.status.success(),
		"tsc rejected the output:\n{}",
		String::from_utf8_lossy(&output.stdout)
	);
}

/// Run the harness natively, as wasm32, and translated, on the same inputs: the
/// translated side through `entry`, a module in `out`. `build` are the native build's
/// arguments, such as `--features`, in the workspace whose manifest is `workspace`.
fn differential(workspace: &Path, package: &str, build: &[&str], out: &Path, entry: &str, cases: u32) {
	let wasm = native(workspace, package, build, &remap());
	compare(&wasm, out, entry, cases, None);
}

/// Build the harness natively, as wasm32, with `RUSTFLAGS` `flags`, returning its module.
fn native(workspace: &Path, package: &str, build: &[&str], flags: &str) -> PathBuf {
	let target_dir = scratch().join("wasm");
	let status = cargo()
		.args([
			"build",
			"--locked",
			"--package",
			package,
			"--target",
			TARGET,
			"--profile",
			PROFILE,
			"--target-dir",
		])
		.arg(&target_dir)
		.args(build)
		.env("CARGO_UNSTABLE_PROFILE_RUSTFLAGS", "true")
		.env("RUSTFLAGS", flags)
		.arg("--manifest-path")
		.arg(workspace)
		.status()
		.expect("running cargo");
	assert!(status.success(), "building {package} for {TARGET} failed");
	target_dir
		.join(TARGET)
		.join(PROFILE)
		.join(format!("{}.wasm", package.replace('-', "_")))
}

/// Run the native module `wasm` and the translation in `out`, through its module `entry`,
/// on the same inputs: `wasm` with wasm-bindgen's JS `glue`, the `_bg.js` its CLI made, if
/// it imports any.
fn compare(wasm: &Path, out: &Path, entry: &str, cases: u32, glue: Option<&Path>) {
	std::fs::write(out.join("package.json"), "{ \"type\": \"module\" }\n").unwrap();
	// One thread: the cases run one at a time, and V8's background compilers and
	// collectors would spend more CPU than they save.
	let output = Command::new("node")
		.arg("--single-threaded")
		.arg(manifest_dir().join("tests").join("differential.ts"))
		.arg(wasm)
		.arg(out.join(entry))
		.arg(cases.to_string())
		.args(glue)
		.output()
		.expect("running node, which the dev shell provides");
	let stdout = String::from_utf8_lossy(&output.stdout);
	let stderr = String::from_utf8_lossy(&output.stderr);
	assert!(
		output.status.success(),
		"{} differs from native Rust:\n{stdout}{stderr}",
		wasm.display()
	);
	println!("{stdout}");
}

