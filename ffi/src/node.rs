//! Node's Node-API addon: the Rust the crate's `node` feature builds into its library,
//! which `node/rt.ts` loads. Each C function the TypeScript calls is a native function of
//! the addon, and each JavaScript implements a C function calling it, each value crossing
//! as [`Cross`] says, so no call makes a JavaScript object.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

use crate::abi::{Ty, is_status};
use crate::glue::rs;
use crate::ir::Int;
use crate::web::{Cross, NodeSig};

/// The Rust runtime the crate's `node` feature builds.
pub(crate) const GLUE_RUNTIME: &str = include_str!("../runtime/node.rs");

/// The addon's glue, `src/node/mod.rs`, of the TypeScript's `calls` and `externs` and the
/// Rust `rust` the web's generator wrote for them; `frees` free the future each takes first,
/// and `kinds` are each object type's free, which the addon calls by its index.
pub(crate) fn glue(
	prefix: &str,
	space: &str,
	rust: &str,
	calls: &BTreeMap<String, NodeSig>,
	externs: &BTreeMap<String, NodeSig>,
	frees: &BTreeSet<String>,
	kinds: &[String],
) -> String {
	let mut calls = calls.clone();
	// What the runtime calls of every API's C ABI. All but a buffer's free, which may drop
	// what JavaScript lent, wait on nothing JavaScript serves, so each runs at once: a call
	// that gives bytes clones them between reading its handles and its call, where
	// JavaScript that closed one would refuse the call after its give.
	let buf = (Ty::Buf, Cross::Copy);
	let void = (Ty::Void, Cross::Void);
	let sig = |params: Vec<(Ty, Cross)>, ret: (Ty, Cross), direct: bool| NodeSig {
		names: vec![String::new(); params.len()],
		params,
		ret,
		direct,
	};
	calls.insert(format!("{prefix}_buf_free"), sig(vec![buf.clone()], void, false));
	calls.insert(format!("{prefix}_buf_copy"), sig(vec![buf.clone()], buf.clone(), true));
	calls.insert(format!("{prefix}_buf_clone"), sig(vec![buf.clone()], buf, true));
	calls.insert(
		format!("{prefix}_contract"),
		sig(vec![], (Ty::Int(Int::U64), Cross::Big), true),
	);
	calls.insert(
		format!("{prefix}_target"),
		sig(vec![], (Ty::Int(Int::U32), Cross::Number), true),
	);
	let mut out = format!(
		"//! Generated by rust2-ffi: the Node-API addon node/index.ts loads. Do not edit.\n\n\
		mod runtime;\n\n\
		pub use runtime::{{acting, waited}};\n\n\
		#[allow(unused_imports, reason = \"the C ABI's structs\")]\n\
		use crate::*;\n\n\
		use std::ffi::{{CStr, c_void}};\n\n\
		use crate::rt;\n\n\
		/// Register the addon, as Node, Bun, and Deno each look it up.\n\
		///\n\
		/// # Safety\n\
		/// Node-API's registration of a module.\n\
		#[unsafe(no_mangle)]\n\
		pub unsafe extern \"C\" fn napi_register_module_v1(env: runtime::Env, exports: runtime::Value) -> runtime::Value {{\n\
		\tunsafe {{ runtime::register(env, exports, CALLS, EXTERNS, FREES) }}\n\
		}}\n\n{rust}"
	);
	let mut table = Vec::new();
	for (i, (name, sig)) in calls.iter().enumerate() {
		stub(&mut out, i, name, sig, frees.contains(name));
		table.push(format!("\t(c\"{name}\", n{i}),\n"));
	}
	table.push(format!("\t(c\"{space}_call\", runtime::native_call),\n"));
	table.push(format!("\t(c\"{space}_abort\", runtime::native_abort),\n"));
	let _ = write!(
		out,
		"/// Each C function the TypeScript calls, by name.\nstatic CALLS: &[(&CStr, runtime::Callback)] = &[\n{}];\n\n",
		table.concat()
	);
	let mut table = String::new();
	for (i, free) in kinds.iter().enumerate() {
		let _ = write!(
			out,
			"/// `{free}`.\nunsafe fn f{i}(p: *const c_void) {{\n\tunsafe {{ {free}(p) }}\n}}\n\n"
		);
		let _ = writeln!(table, "\tf{i},");
	}
	let _ = write!(
		out,
		"/// Each object type's free, by the index its kind names less one.\nstatic FREES: &[unsafe fn(*const c_void)] = &[\n{table}];\n\n"
	);
	let mut names = String::new();
	for (i, (name, sig)) in externs.iter().enumerate() {
		import(&mut out, i, name, sig);
		let _ = writeln!(names, "\tc\"{name}\",");
	}
	let _ = write!(
		out,
		"/// Each C function JavaScript implements, by name, after the runtime's.\nstatic EXTERNS: &[&CStr] = &[\n{names}];\n"
	);
	out
}

/// Whether the C integer type `ty` is signed.
fn signed(ty: &Ty) -> bool {
	match ty {
		Ty::Int(int) => int.rust().starts_with('i'),
		Ty::Enum(_) | Ty::Poll | Ty::Status => true,
		_ => false,
	}
}

/// Whether a value crossing as `cross` crosses through memory, as a struct does.
fn through(cross: Cross) -> bool {
	matches!(cross, Cross::Copy | Cross::Float)
}

/// The native function `n<i>` of the C function `name`: its handles held, then its other
/// arguments, after the place of a struct it returns, each converted to C, then its return
/// converted back once it released its handles and threw any status it failed with; a free
/// frees the id of the future it takes. A `direct` one runs at once, never on a worker.
fn stub(out: &mut String, i: usize, name: &str, sig: &NodeSig, free: bool) {
	let shift = usize::from(through(sig.ret.1));
	let argc = sig.params.iter().filter(|(ty, _)| !is_status(ty)).count() + shift;
	let mut lines = vec![format!("let cx = runtime::Cx::<{argc}>::new(env, info);")];
	// Held before any other argument converts, as a conversion may run JavaScript that closes
	// one, and its address read here, on JavaScript's thread, since a worker may run the call.
	let mut holds = Vec::new();
	let mut held = Vec::new();
	let mut conversions = Vec::new();
	let mut args = Vec::new();
	let mut status = false;
	let mut j = shift;
	for (k, (ty, cross)) in sig.params.iter().enumerate() {
		if is_status(ty) {
			lines.push("let mut s: i32 = 0;".to_string());
			args.push("&mut s".to_string());
			status = true;
			continue;
		}
		let t = rs(ty);
		let e = match cross {
			Cross::Number if *ty == Ty::Bool => format!("cx.int({j}) != 0"),
			Cross::Number => format!("cx.int({j}) as {t}"),
			Cross::Big => format!("cx.big({j}) as {t}"),
			Cross::Wide => {
				let read = if signed(ty) { "i64" } else { "u64" };
				format!("match cx.{read}({j}) {{\n\tOk(v) => v as {t},\n\tErr(()) => return cx.refused(HELD),\n}}")
			}
			Cross::Handle if k == 0 && free => format!("cx.freed({j}) as {t}"),
			Cross::Handle => {
				holds.push(format!(
					"let h{k} = match cx.hold({j}, \"{}\") {{\n\tOk(h) => h,\n\tErr(()) => return runtime::THROWN,\n}};",
					sig.names[k]
				));
				held.push(format!("h{k}"));
				conversions.push(format!("let a{k} = h{k}.p() as {t};"));
				args.push(format!("a{k}"));
				j += 1;
				continue;
			}
			Cross::Token => format!("cx.int({j}) as usize as {t}"),
			Cross::Raw => format!("runtime::from_bits::<{t}>(cx.big({j}) as u64)"),
			Cross::Offset => format!("cx.at({j}) as {t}"),
			Cross::Copy | Cross::Float => format!("cx.at({j}).cast::<{t}>().read()"),
			Cross::OneNumber => format!("runtime::from_bits::<{t}>(cx.int({j}) as u64)"),
			Cross::OneBig => format!("runtime::from_bits::<{t}>(cx.big({j}) as u64)"),
			Cross::Void => unreachable!("no parameter is void"),
		};
		conversions.push(format!("let a{k}: {t} = {e};"));
		args.push(format!("a{k}"));
		j += 1;
	}
	lines.extend(holds);
	let cleanup = format!("({})", held.iter().map(|h| format!("{h},")).collect::<String>());
	lines.extend(conversions.into_iter().map(|line| line.replace("HELD", &cleanup)));
	let call = match sig.direct {
		true => format!("{name}({})", args.join(", ")),
		false => format!("runtime::serve(|| {name}({}))", args.join(", ")),
	};
	let (ty, cross) = &sig.ret;
	let bind = match cross {
		Cross::Void => "",
		_ => "let r = ",
	};
	lines.push(format!("{bind}{call};"));
	// Released before the throw, as a handle's last release may free it, calling JavaScript.
	if !held.is_empty() {
		lines.push(format!(
			"drop(({}));",
			held.iter().map(|h| format!("{h},")).collect::<String>()
		));
	}
	if status {
		lines.push(format!("if s != 0 {{\n\treturn cx.failed(s, \"{name}\");\n}}"));
	}
	let ret = match cross {
		Cross::Void => "cx.undefined()".to_string(),
		Cross::Number if *ty == Ty::Bool => "cx.boolean(r)".to_string(),
		Cross::Number if signed(ty) => "cx.int32(r as i32)".to_string(),
		Cross::Number => "cx.uint32(r as u32)".to_string(),
		Cross::Big => "cx.bigint(r as i64)".to_string(),
		Cross::Wide if signed(ty) => "cx.i64v(r as i64)".to_string(),
		Cross::Wide => "cx.u64v(r as u64)".to_string(),
		Cross::Handle => "cx.indexed(r as *const c_void)".to_string(),
		Cross::Raw | Cross::OneBig => "cx.bigint(runtime::bits(r) as i64)".to_string(),
		Cross::Copy | Cross::Float => format!("cx.at(0).cast::<{}>().write(r);\ncx.undefined()", rs(ty)),
		Cross::OneNumber => "cx.int32(runtime::bits(r) as i32)".to_string(),
		Cross::Token | Cross::Offset => unreachable!("no C function returns a pointer"),
	};
	lines.push(ret);
	let body = lines.join("\n").replace('\n', "\n\t\t");
	let _ = write!(
		out,
		"/// `{name}`.\nunsafe extern \"C\" fn n{i}(env: runtime::Env, info: runtime::Info) -> runtime::Value {{\n\tunsafe {{\n\t\t{body}\n\t}}\n}}\n\n"
	);
}

/// The C function `name` JavaScript implements, the `i`th the addon imports after the
/// runtime's: on JavaScript's thread, it calls the import with each argument converted,
/// after the place of a struct it returns and its data, then copies back what it wrote.
fn import(out: &mut String, i: usize, name: &str, sig: &NodeSig) {
	let mut lines = Vec::new();
	let mut values = Vec::new();
	let sret = through(sig.ret.1);
	if sret {
		lines.push(format!("let r_at = out.slot::<{}>();", rs(&sig.ret.0)));
		values.push("out.offset(r_at)".to_string());
	}
	lines.push("let data = out.token(data);".to_string());
	values.push("data".to_string());
	let mut backs = Vec::new();
	for (k, (ty, cross)) in sig.params.iter().enumerate() {
		let p = format!("p{k}");
		let v = match cross {
			Cross::Number if *ty == Ty::Bool => format!("out.boolean({p})"),
			Cross::Number if signed(ty) => format!("out.int32({p} as i32)"),
			Cross::Number => format!("out.uint32({p} as u32)"),
			Cross::Big => format!("out.bigint({p} as i64)"),
			Cross::Wide if signed(ty) => format!("out.i64v({p} as i64)"),
			Cross::Wide => format!("out.u64v({p} as u64)"),
			Cross::Handle => format!("out.handle({p} as *const c_void)"),
			Cross::Token => format!("out.token({p})"),
			Cross::Raw | Cross::OneBig => format!("out.bigint(runtime::bits({p}) as i64)"),
			Cross::OneNumber => format!("out.int32(runtime::bits({p}) as i32)"),
			Cross::Offset => {
				let copy = !matches!(ty, Ty::Out(_));
				lines.push(format!("let o{k} = out.place({p}.cast_const(), {copy});"));
				if !matches!(ty, Ty::In(_)) {
					backs.push(format!("out.back({p}, o{k});"));
				}
				format!("out.offset(o{k})")
			}
			Cross::Copy | Cross::Float => {
				lines.push(format!("let o{k} = out.value(&{p});"));
				format!("out.offset(o{k})")
			}
			Cross::Void => unreachable!("no parameter is void"),
		};
		lines.push(format!("let v{k} = {v};"));
		values.push(format!("v{k}"));
	}
	let bind = match sig.ret.1 {
		Cross::Void | Cross::Copy | Cross::Float => "",
		_ => "let v = ",
	};
	lines.push(format!(
		"{bind}out.invoke(runtime::FIRST + {i}, &[{}]);",
		values.join(", ")
	));
	lines.extend(backs);
	let (ty, cross) = &sig.ret;
	let t = rs(ty);
	let ret = match cross {
		Cross::Void => String::new(),
		Cross::Number if *ty == Ty::Bool => "out.int(v) != 0".to_string(),
		Cross::Number => format!("out.int(v) as {t}"),
		Cross::Big => format!("out.big(v) as {t}"),
		Cross::Wide if signed(ty) => format!("out.i64(v) as {t}"),
		Cross::Wide => format!("out.u64(v) as {t}"),
		Cross::Handle => format!("out.address(v) as {t}"),
		Cross::Raw | Cross::OneBig => format!("runtime::from_bits::<{t}>(out.big(v) as u64)"),
		Cross::OneNumber => format!("runtime::from_bits::<{t}>(out.int(v) as u64)"),
		Cross::Copy | Cross::Float => format!("out.read::<{t}>(r_at)"),
		Cross::Token | Cross::Offset => unreachable!("no C function returns a pointer"),
	};
	if !ret.is_empty() {
		lines.push(ret);
	}
	let params: String = (sig.params.iter().enumerate())
		.map(|(k, (ty, _))| format!(", p{k}: {}", rs(ty)))
		.collect();
	let _ = write!(
		out,
		"unsafe extern \"C\" fn {name}(data: *mut c_void{params}) -> {t} {{\n\truntime::call(\"{name}\", |out| unsafe {{\n\t\t{}\n\t}})\n}}\n\n",
		lines.join("\n\t\t")
	);
}
