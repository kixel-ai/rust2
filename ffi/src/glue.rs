//! The Rust side of the C ABI: a crate of `extern "C"` functions over the facade, with the runtime beside it and the header in `include/`.
//!
//! Each function lifts its C arguments to Rust values, calls the Rust item by its path,
//! and lowers the result. A value is copied in from the caller's memory, which Rust
//! never frees, and lowered into memory the caller frees. A handle is borrowed as the
//! receiver or parameter is, or moved out of when taken by value.

use std::fmt::Write;
use std::path::Path;

use crate::abi::{self, Abi, CFG, Ty};
use crate::config::Package;
use crate::ir::{
	Access, Closure, Collection, Family, Function, Literal, Mutability, On, Receiver, Task, TaskKind, Traits, Type,
};

const RUNTIME: &str = include_str!("../runtime/rt.rs");

/// The crate's build script, which refuses to build for a target but `targets`, on which an
/// item a target compiles would be missing, or one it leaves out left over, and tells the
/// crate which it builds for, as the `cfg` [`CFG`]. On macOS, a CPython extension leaves
/// Python's symbols for the interpreter that loads it to resolve.
fn build(targets: &[String]) -> String {
	let list: Vec<String> = targets.iter().map(|t| format!("{t:?}")).collect();
	let list = list.join(", ");
	let names = targets.join(", ");
	format!(
		"// Generated by rust2-ffi. Do not edit.\n\n\
		fn main() {{\n\
		\tlet target = std::env::var(\"TARGET\").expect(\"cargo sets TARGET\");\n\
		\tprintln!(\"cargo::rustc-check-cfg=cfg({CFG}, values({}))\");\n\
		\tif ![{list}].contains(&target.as_str()) {{\n\
		\t\tpanic!(\"exported for {names}, not {{target}}: export again with --target {{target}}\");\n\
		\t}}\n\
		\tprintln!(\"cargo::rustc-cfg={CFG}=\\\"{{target}}\\\"\");\n\
		\t#[cfg(feature = \"python\")]\n\
		\tpyo3_build_config::add_extension_module_link_args();\n\
		}}\n",
		list.replace('"', "\\\"")
	)
}

/// The name the crate depends on the facade by, its root suffixed: the facade may be named
/// `bytes` or `std`, or as the crate itself, which the crate names too.
fn dependency(krate: &str) -> String {
	format!("{krate}_export")
}

/// The name the crate depends on a foreign type's crate by, apart from the facade's even
/// when the facade shares that crate's name.
fn foreign(krate: &str) -> String {
	format!("{krate}_foreign")
}

/// The Rust path of a foreign type, by its own crate's path: std's as std names it, and
/// another crate's through the name the crate depends on it by.
fn foreign_path(path: &[String]) -> String {
	let krate = match path[0].as_str() {
		"std" => "std".to_string(),
		krate => foreign(krate),
	};
	format!("::{krate}") + &path[1..].iter().map(|s| format!("::{s}")).collect::<String>()
}

/// The Rust path of a collection, without its arguments.
fn collection(c: Collection) -> String {
	match c {
		Collection::Vec => "::std::vec::Vec".to_string(),
		Collection::BTreeSet => "::std::collections::BTreeSet".to_string(),
		Collection::BTreeMap => "::std::collections::BTreeMap".to_string(),
		Collection::JsonMap => format!("::{}::Map", foreign("serde_json")),
	}
}

/// The Rust spelling of a C type.
pub fn rs(ty: &Ty) -> String {
	match ty {
		Ty::Void => "()".to_string(),
		Ty::Bool => "bool".to_string(),
		Ty::Int(int) => int.rust().to_string(),
		Ty::F32 => "f32".to_string(),
		Ty::F64 => "f64".to_string(),
		Ty::Char => "u32".to_string(),
		Ty::Buf => "rt::Buf".to_string(),
		Ty::U128 => "rt::U128".to_string(),
		Ty::Duration => "rt::Duration".to_string(),
		Ty::SocketAddr => "rt::SocketAddr".to_string(),
		Ty::Struct(name) => name.clone(),
		// A C enum is an `int`.
		Ty::Enum(_) | Ty::Poll => "i32".to_string(),
		Ty::Handle { .. } => "*const ::std::ffi::c_void".to_string(),
		Ty::Future(_) => "*mut rt::Future".to_string(),
		Ty::Waker => "rt::Waker".to_string(),
		Ty::ForeignFuture => "rt::ForeignFuture".to_string(),
		Ty::ForeignReader => "rt::ForeignReader".to_string(),
		Ty::Out(inner) => format!("*mut {}", rs(inner)),
		Ty::In(inner) => format!("*const {}", rs(inner)),
		Ty::Fn(params, ret) => {
			let params: Vec<String> = std::iter::once("*mut ::std::ffi::c_void".to_string())
				.chain(params.iter().map(rs))
				.collect();
			format!("Option<unsafe extern \"C\" fn({}) -> {}>", params.join(", "), rs(ret))
		}
		Ty::Data => "*mut ::std::ffi::c_void".to_string(),
	}
}

/// The crate that builds the C ABI.
pub struct Crate<'a> {
	pub abi: &'a Abi<'a>,
	/// The facade, a dependency of the crate.
	pub facade: &'a Package,
	/// The `[patch]` table the crate's own workspace resolves the exports with, as the
	/// check did.
	pub patch: &'a str,
}

impl Crate<'_> {
	/// The facade's package name.
	fn packages(&self) -> String {
		self.facade.name.clone()
	}

	/// Write the crate into `out`: `Cargo.toml`, `src/`, `include/<prefix>.h` and `.hpp`,
	/// `kotlin/<prefix>.kt`, whose JNI functions the crate's `kotlin` feature builds,
	/// `python/<prefix>.py`, whose CPython extension its `python` feature builds,
	/// `swift/<prefix>.swift` with the clang module it imports the header through, and
	/// `go/<prefix>.go`, and `dart/<prefix>.dart`, whose glue its `dart` feature builds.
	pub fn write(&self, out: &Path) -> Result<(), String> {
		// Cargo unifies in what the facade enables in its dependencies.
		let facade = self.facade;
		let mut features: Vec<String> = facade.features.iter().map(|f| format!("{f:?}")).collect();
		features.sort();
		let dependencies = format!(
			"{} = {{ package = {:?}, path = {:?}, default-features = false, features = [{}] }}\n",
			dependency(&facade.root()),
			facade.name,
			facade.dir.display().to_string(),
			features.join(", ")
		);
		// A foreign type, exported as an object when no export is its crate, resolves to the
		// version the exports build with, as `bytes` does: one per major version per
		// resolution. Its features are the ones the exports enable, so the glue adds none.
		let api = self.abi.api;
		let foreign: String = [
			("url", "url", "2"),
			("serde_json", "serde_json", "1"),
			("tracing_core", "tracing-core", "0.1"),
		]
		.into_iter()
		.filter(|(krate, ..)| {
			(api.objects.iter()).any(|o| o.foreign && o.path[0] == *krate)
				|| (api.enums.iter()).any(|e| e.foreign && e.path[0] == *krate)
		})
		.map(|(krate, package, version)| {
			format!(
				"{} = {{ package = \"{package}\", version = \"{version}\", default-features = false }}\n",
				foreign(krate)
			)
		})
		.collect();
		let dependencies = format!("{dependencies}{foreign}");
		// The facade's oldest toolchain is the crate's, which cargo sets as rustc compiles it,
		// though no older than the crate's edition needs; cargo checks the value's form.
		let rust_version = match std::env::var("CARGO_PKG_RUST_VERSION") {
			Ok(version) if !version.is_empty() => {
				let parts: Vec<u64> = version.split('.').map(|p| p.parse().unwrap_or(0)).collect();
				let version = if parts[..] < [1, 85][..] { "1.85" } else { &version };
				format!("rust-version = {version:?}\n")
			}
			_ => String::new(),
		};
		let manifest = format!(
			"# Generated by rust2-ffi: the C ABI of the pub API of {packages}.\n\
			[package]\n\
			name = \"{package}-ffi\"\n\
			version = \"0.0.0\"\n\
			edition = \"2024\"\n\
			{rust_version}\
			publish = false\n\
			\n\
			[lib]\n\
			name = \"{lib}\"\n\
			crate-type = [\"staticlib\", \"cdylib\"]\n\
			\n\
			[dependencies]\n\
			{dependencies}\
			bytes = \"1\"\n\
			jni-sys = {{ version = \"0.4\", optional = true }}\n\
			pyo3-ffi = {{ version = \"0.30\", optional = true, features = [\"abi3-py311\", \"extension-module\"] }}\n\
			smallvec = {{ version = \"1.16\", optional = true }}\n\
			\n\
			[build-dependencies]\n\
			pyo3-build-config = {{ version = \"0.30\", optional = true }}\n\
			\n\
			[features]\n\
			# The JNI functions kotlin/{lib}.kt calls.\n\
			kotlin = [\"dep:jni-sys\"]\n\
			# The CPython extension python/{lib}.py loads.\n\
			python = [\"dep:pyo3-ffi\", \"dep:pyo3-build-config\", \"dep:smallvec\"]\n\
			# What dart/{lib}.dart calls that `dart:ffi` lacks.\n\
			dart = []\n\
			\n\
			[workspace]\n\
			{patch}",
			patch = self.patch,
			package = facade.name,
			packages = self.packages(),
			lib = self.abi.prefix,
		);
		let (header, contract) = crate::c::header(self.abi, &self.packages());
		let cpp = crate::cpp::header(self.abi, &self.packages())?;
		let kotlin = crate::kotlin::generate(self.abi, &self.packages(), contract)?;
		let python = crate::python::generate(self.abi, &self.packages(), contract)?;
		let swift = crate::swift::generate(self.abi, &self.packages(), contract)?;
		let (module, go_mod) = go_module(out, &self.abi.prefix)?;
		let go = crate::go::generate(self.abi, &self.packages(), contract, &module)?;
		let dart = crate::dart::generate(self.abi, &self.packages(), contract)?;
		let mut generator = Gen {
			abi: self.abi,
			packages: self.packages(),
			contract,
			dependency: dependency(&facade.root()),
			lends: false,
			on: On::ALL,
			out: String::new(),
		};
		generator.lib();
		crate::driver::write(&out.join("Cargo.toml"), &manifest)?;
		crate::driver::write(&out.join("src/lib.rs"), &generator.out)?;
		crate::driver::write(&out.join("build.rs"), &build(&self.abi.api.targets))?;
		crate::driver::write(&out.join("src/rt.rs"), RUNTIME)?;
		crate::driver::write(&out.join("include").join(format!("{}.h", self.abi.prefix)), &header)?;
		crate::driver::write(&out.join("include").join(format!("{}.hpp", self.abi.prefix)), &cpp)?;
		crate::driver::write(&out.join("src/jni/mod.rs"), &kotlin.glue)?;
		crate::driver::write(&out.join("src/jni/rt.rs"), crate::kotlin::GLUE_RUNTIME)?;
		crate::driver::write(
			&out.join("kotlin").join(format!("{}.kt", self.abi.prefix)),
			&kotlin.kotlin,
		)?;
		crate::driver::write(
			&out.join("kotlin").join(format!("{}.pro", self.abi.prefix)),
			&kotlin.rules,
		)?;
		crate::driver::write(&out.join("src/python/mod.rs"), &python.glue)?;
		crate::driver::write(&out.join("src/python/rt.rs"), crate::python::GLUE_RUNTIME)?;
		crate::driver::write(
			&out.join("python").join(format!("{}.py", self.abi.prefix)),
			&python.python,
		)?;
		crate::driver::write(&out.join("src/dart/mod.rs"), &dart.glue)?;
		crate::driver::write(&out.join("src/dart/runtime.rs"), crate::dart::GLUE_RUNTIME)?;
		crate::driver::write(&out.join("dart").join(format!("{}.dart", self.abi.prefix)), &dart.dart)?;
		let swift_dir = out.join("swift");
		crate::driver::write(&swift_dir.join(format!("{}.swift", self.abi.prefix)), &swift.swift)?;
		crate::driver::write(&swift_dir.join("module.modulemap"), &swift.modulemap)?;
		crate::driver::write(
			&swift_dir.join(format!("{}_atomics.h", self.abi.prefix)),
			&swift.atomics,
		)?;
		// What an earlier export wrote may name packages this one has not.
		let go_dir = out.join("go");
		if go_dir.exists() {
			std::fs::remove_dir_all(&go_dir).map_err(|err| format!("removing {}: {err}", go_dir.display()))?;
		}
		if let Some(go_mod) = go_mod {
			crate::driver::write(&go_dir.join("go.mod"), &go_mod)?;
		}
		for (path, text) in go {
			crate::driver::write(&go_dir.join(path), &text)?;
		}
		Ok(())
	}
}

/// The path the module directive of the `go.mod` at `path` declares, as the go command reads it.
fn module_path(path: &Path) -> Result<String, String> {
	#[derive(serde::Deserialize)]
	struct GoMod {
		#[serde(rename = "Module")]
		module: Option<Module>,
	}
	#[derive(serde::Deserialize)]
	struct Module {
		#[serde(rename = "Path")]
		path: String,
	}
	let output = std::process::Command::new("go")
		.args(["mod", "edit", "-json"])
		.arg(path)
		// Reading a go.mod that names a newer Go must not download that toolchain.
		.env("GOTOOLCHAIN", "local")
		.output()
		.map_err(|err| match err.kind() {
			std::io::ErrorKind::NotFound => format!(
				"the go command is not on PATH: the export reads the module of {}, above --out, with `go mod edit -json`",
				path.display()
			),
			_ => format!("running go mod edit -json {}: {err}", path.display()),
		})?;
	if !output.status.success() {
		return Err(format!(
			"go mod edit -json {} failed:\n{}",
			path.display(),
			String::from_utf8_lossy(&output.stderr).trim_end()
		));
	}
	let go_mod: GoMod = serde_json::from_slice(&output.stdout)
		.map_err(|err| format!("reading go mod edit -json {}: {err}", path.display()))?;
	go_mod
		.module
		.map(|module| module.path)
		.ok_or_else(|| format!("{} declares no module", path.display()))
}

/// The import path of `<out>/go`, from the `go.mod` of the module above it, or else the
/// module `prefix`, with the `go.mod` declaring it there.
fn go_module(out: &Path, prefix: &str) -> Result<(String, Option<String>), String> {
	std::fs::create_dir_all(out).map_err(|err| format!("creating {}: {err}", out.display()))?;
	let out = std::fs::canonicalize(out).map_err(|err| format!("reading {}: {err}", out.display()))?;
	for dir in out.ancestors() {
		let path = dir.join("go.mod");
		if !path.is_file() {
			continue;
		}
		let module = module_path(&path)?;
		let rest = out.join("go");
		let rest = rest.strip_prefix(dir).expect("an ancestor holds it");
		let rest: Vec<String> = rest
			.components()
			.map(|c| c.as_os_str().to_string_lossy().into_owned())
			.collect();
		return Ok((format!("{module}/{}", rest.join("/")), None));
	}
	Ok((prefix.to_string(), Some(format!("module {prefix}\n\ngo 1.24\n"))))
}

struct Gen<'a> {
	abi: &'a Abi<'a>,
	/// The exported packages, for the docs.
	packages: String,
	/// The header's contract, which `<prefix>_contract` returns.
	contract: u64,
	/// The name the crate depends on the facade by.
	dependency: String,
	/// Whether the function being written returns a borrow lent from its receiver's
	/// handle, which `lender` holds.
	lends: bool,
	/// The targets of the item being written, which compile what names its Rust types.
	on: On,
	out: String,
}

impl Gen<'_> {
	/// A C type, or anything else every target compiles.
	fn line(&mut self, line: impl AsRef<str>) {
		self.out.push_str(line.as_ref());
		self.out.push('\n');
	}

	fn cfg(&self, on: On) -> Option<String> {
		self.abi.cfg(on)
	}

	/// What names the facade's types, on the targets of the item being written.
	fn item(&mut self, item: String) {
		if let Some(cfg) = self.cfg(self.on) {
			self.out.push_str(&format!("#[cfg({cfg})]\n"));
		}
		self.line(item);
	}

	/// A C function, which on a target its item is not on fails when called: the binding
	/// serves those targets too, and checks a call's target before making it.
	fn export(&mut self, function: String) {
		let Some(cfg) = self.cfg(self.on) else {
			return self.line(function);
		};
		let at = function.find(" extern \"C\" fn ").expect("a C function");
		let head = &function[..at + function[at..].find(" {\n").expect("a C function's body")];
		let name = &head[head.rfind(" fn ").expect("a C function") + 4..];
		let name = &name[..name.find('(').expect("a C function's parameters")];
		let stub = format!(
			"#[cfg(not({cfg}))]\n#[allow(unused_variables, reason = \"a call fails before reading any\")]\n{head} {{\n\trt::fail(\"{name}\", \"it is not on this library's target\")\n}}\n"
		);
		self.out.push_str(&format!("#[cfg({cfg})]\n"));
		self.line(function);
		self.line(stub);
	}

	/// The `#[cfg]` of a match arm for `variant`, if not on every target.
	fn arm(&self, on: On) -> String {
		self.cfg(on)
			.map(|cfg| format!("\n\t\t#[cfg({cfg})]"))
			.unwrap_or_default()
	}

	/// A Rust path of the facade's, through the crate's dependency on it.
	fn path(&self, path: &[String]) -> String {
		format!("::{}", self.dependency) + &path[1..].iter().map(|s| format!("::{s}")).collect::<String>()
	}

	/// An object's Rust type: its lifetimes `'static`, as the handle holds it.
	fn object_path(&self, i: usize) -> String {
		self.rust(&Type::Object(i))
	}

	/// The Rust spelling of a type a callback's method takes or returns, or a type
	/// argument: a type with its instance's arguments, and an object's lifetimes `'static`.
	fn rust(&self, ty: &Type) -> String {
		let api = self.abi.api;
		let generic = |path: &[String], lifetimes: usize, args: &[Type]| {
			let path = self.path(path);
			let mut params = vec!["'static".to_string(); lifetimes];
			params.extend(args.iter().map(|arg| self.rust(arg)));
			match params.is_empty() {
				true => path,
				false => format!("{path}::<{}>", params.join(", ")),
			}
		};
		match ty {
			Type::Unit => "()".to_string(),
			Type::Bool => "bool".to_string(),
			Type::Int(int) => int.rust().to_string(),
			Type::NonZero(int) => format!("::std::num::NonZero<{}>", int.rust()),
			Type::U128 => "u128".to_string(),
			Type::F32 => "f32".to_string(),
			Type::F64 => "f64".to_string(),
			Type::Char => "char".to_string(),
			Type::Str => "str".to_string(),
			Type::String => "::std::string::String".to_string(),
			Type::Slice => "[u8]".to_string(),
			Type::Vec => "::std::vec::Vec<u8>".to_string(),
			Type::Bytes => "::bytes::Bytes".to_string(),
			Type::Duration => "::std::time::Duration".to_string(),
			Type::Array(n) => format!("[u8; {n}]"),
			Type::Path => "::std::path::Path".to_string(),
			Type::PathBuf => "::std::path::PathBuf".to_string(),
			Type::SocketAddr(Family::Any) => "::std::net::SocketAddr".to_string(),
			Type::SocketAddr(Family::V4) => "::std::net::SocketAddrV4".to_string(),
			Type::SocketAddr(Family::V6) => "::std::net::SocketAddrV6".to_string(),
			Type::List(c, inner) => match (c, &**inner) {
				// A map's items are its key and value.
				(Collection::BTreeMap | Collection::JsonMap, Type::Tuple(pair)) => {
					format!("{}<{}, {}>", collection(*c), self.rust(&pair[0]), self.rust(&pair[1]))
				}
				_ => format!("{}<{}>", collection(*c), self.rust(inner)),
			},
			Type::Option(inner) => format!("Option<{}>", self.rust(inner)),
			Type::Ref(Mutability::Not, inner) => format!("&{}", self.rust(inner)),
			Type::Ref(Mutability::Mut, inner) => format!("&mut {}", self.rust(inner)),
			Type::Record(i) => generic(&api.records[*i].path, 0, &api.records[*i].args),
			Type::Enum(i) if api.enums[*i].foreign => foreign_path(&api.enums[*i].path),
			Type::Enum(i) => generic(&api.enums[*i].path, 0, &api.enums[*i].args),
			Type::Object(i) if api.objects[*i].opaque => "rt::Opaque".to_string(),
			Type::Object(i) if api.objects[*i].foreign => foreign_path(&api.objects[*i].path),
			Type::Object(i) => generic(&api.objects[*i].path, api.objects[*i].lifetimes, &api.objects[*i].args),
			// A negative argument is an expression, which Rust takes only in braces.
			Type::Const(Literal::Int(_, v)) if *v < 0 => format!("{{{v}}}"),
			Type::Const(value) => value.to_string(),
			other => unreachable!("no callback or type argument is {other:?}"),
		}
	}

	/// The Rust value of type `ty` that the C value `e` holds, copied out of it.
	fn lift(&self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Const(_) => unreachable!("a const argument is no value"),
			Type::Unit => e.to_string(),
			Type::Bool | Type::Int(_) | Type::F32 | Type::F64 => e.to_string(),
			Type::NonZero(_) => {
				format!("::std::num::NonZero::new({e}).unwrap_or_else(|| rt::fail(w, \"a NonZero is zero\"))")
			}
			Type::Char => format!("rt::char({e}, w)"),
			Type::Str | Type::String => format!("unsafe {{ {e}.str(w) }}.to_owned()"),
			Type::Slice | Type::Vec => format!("unsafe {{ {e}.bytes(w) }}.to_vec()"),
			Type::Bytes => format!("::bytes::Bytes::copy_from_slice(unsafe {{ {e}.bytes(w) }})"),
			Type::Path | Type::PathBuf => format!("unsafe {{ {e}.path(w) }}.to_path_buf()"),
			Type::U128 => format!("{e}.lift()"),
			Type::Array(_) => format!("{e}.items"),
			Type::Duration | Type::SocketAddr(Family::Any) => format!("{e}.lift(w)"),
			Type::SocketAddr(Family::V4) => format!("{e}.lift_v4(w)"),
			Type::SocketAddr(Family::V6) => format!("{e}.lift_v6(w)"),
			Type::Waker => format!("{e}.lift()"),
			Type::Future | Type::Reader => format!("{e}.lift(w)"),
			Type::List(c, inner) => format!(
				"unsafe {{ {e}.items(w) }}.iter().map(|c| {}).collect::<{}<{}>>()",
				self.lift(inner, "(*c)"),
				collection(*c),
				match c {
					Collection::BTreeMap | Collection::JsonMap => "_, _",
					Collection::Vec | Collection::BTreeSet => "_",
				}
			),
			// A foreign enum's option converts into its filter, as `tracing::LevelFilter`.
			Type::Option(inner) if self.filtered(inner) => format!(
				"::std::convert::From::from(if {e}.some {{ Some({}) }} else {{ None }})",
				self.lift(inner, &format!("{e}.value"))
			),
			Type::Option(inner) => match inner.base() {
				Type::Object(_) => format!("if {e}.is_null() {{ None }} else {{ Some({}) }}", self.lift(inner, e)),
				base if Abi::nullable(base) => {
					format!("if {e}.is_none() {{ None }} else {{ Some({}) }}", self.lift(inner, e))
				}
				_ => format!(
					"if {e}.some {{ Some({}) }} else {{ None }}",
					self.lift(inner, &format!("{e}.value"))
				),
			},
			Type::Box(inner) => format!("::std::boxed::Box::new({})", self.lift(inner, e)),
			Type::Ref(_, inner) => self.lift(inner, e),
			Type::Record(i) => format!("lift_{}(&{e}, w)", self.abi.record(*i)),
			Type::Enum(i) => match self.abi.api.enums[*i].plain() {
				true => format!("lift_{}({e}, w)", self.abi.enumeration(*i)),
				false => format!("lift_{}(&{e}, w)", self.abi.enumeration(*i)),
			},
			Type::Object(i) if self.abi.api.objects[*i].opaque => {
				format!("unsafe {{ rt::Object::<rt::Opaque>::take({e}, w) }}.arc(w)")
			}
			Type::Object(i) => match self.abi.api.objects[*i].copy {
				true => format!(
					"*unsafe {{ rt::Object::<{}>::{}({e}, w) }}",
					self.object_path(*i),
					self.shared(*i)
				),
				false => format!("unsafe {{ rt::Object::<{}>::take({e}, w) }}", self.object_path(*i)),
			},
			Type::Callback(i, form) => abi::dyn_wrap(*form, &format!("Foreign_{}({e})", self.abi.callback(*i))),
			Type::Closure(closure) => self.closure(closure, e),
			Type::Range(_) => format!("{e}.lift()"),
			Type::Bound(_) | Type::Bounds(_) => format!("{e}.lift(w)"),
			Type::Tuple(elements) => {
				// The trailing comma makes `(x,)` a tuple, not parentheses.
				let lifted: Vec<String> = (elements.iter().enumerate())
					.map(|(n, ty)| format!("{},", self.lift(ty, &format!("{e}._{n}"))))
					.collect();
				format!("({})", lifted.concat())
			}
		}
	}

	/// The Rust closure calling the function C implements as `e`, with its data `e_data`,
	/// which lends each object the closure takes as a handle for that call. A kept one frees
	/// its data with `e_free` once dropped.
	fn closure(&self, closure: &Closure, e: &str) -> String {
		let typed: Vec<String> = (closure.params.iter().enumerate())
			.map(|(n, ty)| format!("c{n}: {}", self.rust(ty)))
			.collect();
		// Each object the closure takes, and how it is lent: a `Copy` one by value too.
		let lent = |ty: &Type| match ty {
			Type::Ref(m, inner) => match (&**inner, m) {
				(&Type::Object(i), Mutability::Mut) => Some((i, "lend_mut", "")),
				(&Type::Object(i), Mutability::Not) if self.abi.api.objects[i].sync => Some((i, "lend", "")),
				(&Type::Object(i), Mutability::Not) => Some((i, "lend_local", "")),
				_ => None,
			},
			&Type::Object(i) if self.abi.api.objects[i].sync => Some((i, "lend", "&")),
			&Type::Object(i) => Some((i, "lend_local", "&")),
			_ => None,
		};
		let mut args: Vec<String> = std::iter::once("data.get()".to_string())
			.chain(closure.params.iter().enumerate().map(|(n, ty)| match lent(ty) {
				Some(_) => format!("h{n}"),
				None => self.view(ty, &format!("c{n}")),
			}))
			.collect();
		// A `Result` writes its value and its error through out pointers.
		let mut outs = String::new();
		if let Some(err) = &closure.err {
			if closure.ok != Type::Unit {
				outs.push_str(&format!(
					"let mut out = ::std::mem::MaybeUninit::<{}>::zeroed();\n\t\t\t",
					rs(&self.abi.ty(&closure.ok))
				));
				args.push("out.as_mut_ptr()".to_string());
			}
			outs.push_str(&format!(
				"let mut err = ::std::mem::MaybeUninit::<{}>::zeroed();\n\t\t\t",
				rs(&self.abi.ty(err))
			));
			args.push("err.as_mut_ptr()".to_string());
		}
		let mut call = format!("unsafe {{ f({}) }}", args.join(", "));
		for (n, ty) in closure.params.iter().enumerate().rev() {
			if let Some((i, lend, by)) = lent(ty) {
				call = format!(
					"rt::Object::<{}>::{lend}({by}c{n}, w, |h{n}| {call})",
					self.object_path(i)
				);
			}
		}
		let ret = self.rust(&closure.ok);
		let (ret, lifted) = match &closure.err {
			None => (ret, self.returned(&closure.ok, "result")),
			Some(err) => {
				let ok = match closure.ok {
					Type::Unit => "()".to_string(),
					_ => self.returned(&closure.ok, "unsafe { out.assume_init() }"),
				};
				(
					format!("::std::result::Result<{ret}, {}>", self.rust(err)),
					format!(
						"match result {{\n\t\t\t\ttrue => Ok({ok}),\n\t\t\t\tfalse => Err({}),\n\t\t\t}}",
						self.returned(err, "unsafe { err.assume_init() }")
					),
				)
			}
		};
		let data = match closure.kept {
			true => format!("rt::Kept::new({e}_data, {e}_free)"),
			false => format!("rt::Data::new({e}_data)"),
		};
		format!(
			"{{\n\t\tlet f = {e}.unwrap_or_else(|| rt::fail(w, \"a function is null\"));\n\t\tlet data = {data};\n\t\tmove |{}| -> {ret} {{\n\t\t\t{outs}let result = {call};\n\t\t\t{lifted}\n\t\t}}\n\t}}",
			typed.join(", "),
		)
	}

	/// The Rust value a closure C implements returned as the C value `e`, which Rust then
	/// owns: a buffer `<prefix>_buf_copy` made, or a handle, out of which it copies a
	/// `Copy` object before freeing it.
	fn returned(&self, ty: &Type, e: &str) -> String {
		match ty {
			Type::String => format!("unsafe {{ {e}.take_string(w) }}"),
			Type::Object(i) => format!("unsafe {{ rt::Object::<{}>::returned({e}, w) }}", self.object_path(*i)),
			Type::Option(inner) => format!(
				"{{ let r = {e}; if r.is_null() {{ None }} else {{ Some({}) }} }}",
				self.returned(inner, "r")
			),
			ty => self.lift(ty, e),
		}
	}

	/// Whether an option of `ty` may be a foreign enum's filter, such as `tracing::LevelFilter`
	/// of `tracing::Level`, which converts to and from the option.
	fn filtered(&self, ty: &Type) -> bool {
		matches!(ty, Type::Enum(i) if self.abi.api.enums[*i].foreign)
	}

	/// How a call borrows object `i` shared: across threads if it is `Sync`, else on one.
	fn shared(&self, i: usize) -> &'static str {
		match self.abi.api.objects[i].sync {
			true => "borrow",
			false => "borrow_local",
		}
	}

	/// The C value of the Rust value `e` of type `ty`, which the caller frees.
	fn lower(&self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Const(_) => unreachable!("a const argument is no value"),
			Type::Unit => "()".to_string(),
			Type::Bool | Type::Int(_) | Type::F32 | Type::F64 => e.to_string(),
			Type::NonZero(_) => format!("({e}).get()"),
			Type::Char => format!("{e} as u32"),
			Type::Str => format!("rt::Buf::string({e}.to_owned())"),
			Type::String => format!("rt::Buf::string({e})"),
			Type::Slice => format!("rt::Buf::vec({e}.to_vec())"),
			Type::Vec => format!("rt::Buf::vec({e})"),
			Type::Bytes => format!("rt::Buf::owned({e})"),
			Type::Path => format!("rt::Buf::path_buf({e}.to_path_buf())"),
			Type::PathBuf => format!("rt::Buf::path_buf({e})"),
			Type::U128 => format!("rt::U128::lower({e})"),
			Type::Duration => format!("rt::Duration::lower({e})"),
			Type::Array(n) => format!("{} {{ items: {e} }}", self.abi.array(*n)),
			Type::SocketAddr(_) => format!("rt::SocketAddr::lower(::std::net::SocketAddr::from({e}))"),
			Type::List(_, inner) => format!(
				"rt::List::owned(::std::iter::IntoIterator::into_iter({e}).map(|v| {}).collect())",
				self.lower(inner, "v")
			),
			Type::Option(inner) => {
				// A foreign enum's filter, as `tracing::LevelFilter`, converts into its option.
				let e = &match self.filtered(inner) {
					true => format!("::std::option::Option::<{}>::from({e})", self.rust(inner)),
					false => e.to_string(),
				};
				let none = match inner.base() {
					Type::Object(_) => "::std::ptr::null()".to_string(),
					base if Abi::is_buf(base) => "rt::Buf::NONE".to_string(),
					Type::List(..) => "rt::List::NONE".to_string(),
					_ => {
						let name = self.abi.option(inner);
						return format!(
							"match {e} {{ Some(v) => {name} {{ some: true, value: {} }}, None => {name} {{ some: false, value: unsafe {{ ::std::mem::zeroed() }} }} }}",
							self.lower(inner, "v")
						);
					}
				};
				format!("match {e} {{ Some(v) => {}, None => {none} }}", self.lower(inner, "v"))
			}
			Type::Box(inner) => self.lower(inner, &format!("*{e}")),
			Type::Ref(_, inner) => match &**inner {
				Type::Str | Type::Slice | Type::Path => self.lower(inner, e),
				Type::Object(i) if self.lends => {
					format!("rt::Object::<{}>::lent({e}, lender)", self.object_path(*i))
				}
				// A handle in the clone is a new handle, and a slice's clone a `Vec`.
				inner => self.lower(inner, &format!("::std::borrow::ToOwned::to_owned({e})")),
			},
			Type::Record(i) => format!("lower_{}({e})", self.abi.record(*i)),
			Type::Enum(i) => format!("lower_{}({e})", self.abi.enumeration(*i)),
			Type::Object(i) if self.abi.api.objects[*i].opaque => format!("rt::Object::new(rt::Opaque::new({e}))"),
			Type::Object(_) => format!("rt::Object::new({e})"),
			Type::Callback(..) | Type::Closure(..) => unreachable!("a callback is never returned"),
			Type::Waker => format!("rt::Waker::lower({e})"),
			Type::Future | Type::Reader => unreachable!("{ty:?} is never returned"),
			Type::Range(_) => format!("rt::Range::lower({e})"),
			Type::Bound(_) => format!("rt::Bound::lower({e})"),
			Type::Bounds(_) => format!("rt::Bounds::lower({e})"),
			Type::Tuple(elements) => {
				let names: Vec<String> = (0..elements.len()).map(|n| format!("t{n},")).collect();
				let fields: Vec<String> = (elements.iter().enumerate())
					.map(|(n, ty)| format!("_{n}: {}", self.lower(ty, &format!("t{n}"))))
					.collect();
				format!(
					"match {e} {{ ({}) => {} {{ {} }} }}",
					names.concat(),
					self.abi.tuple(elements),
					fields.join(", ")
				)
			}
		}
	}

	/// What frees the parts of the C value `e` that Rust allocated, if any.
	fn free(&self, ty: &Type, e: &str) -> Option<String> {
		match ty {
			_ if Abi::is_buf(ty) => Some(format!("unsafe {{ {e}.free() }};")),
			Type::List(_, inner) => {
				let each = self.free(inner, "c").unwrap_or_default();
				Some(format!(
					"unsafe {{ {e}.free(\"{}_free\", |c| {{ let _ = c; {each} }}) }};",
					self.abi.list(inner)
				))
			}
			Type::Option(inner) => match inner.base() {
				base if Abi::is_buf(base) => Some(format!("unsafe {{ {e}.free() }};")),
				// A null handle or array frees nothing.
				Type::Object(_) | Type::List(..) => self.free(inner, e),
				_ => self
					.free(inner, &format!("{e}.value"))
					.map(|free| format!("if {e}.some {{ {free} }}")),
			},
			Type::Box(inner) => self.free(inner, e),
			Type::Tuple(elements) => {
				let frees: Vec<String> = (elements.iter().enumerate())
					.filter_map(|(n, ty)| self.free(ty, &format!("{e}._{n}")))
					.collect();
				(!frees.is_empty()).then(|| frees.join(" "))
			}
			Type::Object(i) => Some(format!(
				"unsafe {{ rt::Object::<{}>::free({e}) }};",
				self.object_path(*i)
			)),
			Type::Record(i) if self.owns(ty) => Some(format!("free_{}({e});", self.abi.record(*i))),
			Type::Enum(i) if self.owns(ty) => Some(format!("free_{}({e});", self.abi.enumeration(*i))),
			_ => None,
		}
	}

	/// Whether a value of `ty` holds memory Rust allocated.
	fn owns(&self, ty: &Type) -> bool {
		match ty {
			_ if Abi::is_buf(ty) => true,
			Type::Object(_) | Type::List(..) => true,
			Type::Option(inner) | Type::Box(inner) => self.owns(inner),
			Type::Tuple(elements) => elements.iter().any(|ty| self.owns(ty)),
			Type::Record(i) => self.abi.api.records[*i].fields.iter().any(|f| self.owns(&f.ty)),
			Type::Enum(i) => self.abi.api.enums[*i]
				.variants
				.iter()
				.any(|v| v.fields.iter().any(|f| self.owns(&f.ty))),
			_ => false,
		}
	}

	fn lib(&mut self) {
		let api = self.abi.api;
		self.line(format!(
			"//! Generated by rust2-ffi: the C ABI of the pub API of {}. Do not edit.\n",
			self.packages
		));
		self.line("#![allow(non_camel_case_types, non_snake_case, reason = \"the C names\")]");
		self.line("#![allow(unused_unsafe, reason = \"every conversion is in its own block\")]");
		self.line("#![allow(unused_parens, reason = \"each element is lifted from `(*c)`\")]");
		self.line("#![allow(clippy::all, reason = \"generated\")]");
		self.line("#![allow(dead_code, reason = \"the runtime serves every API\")]\n");
		self.line("mod rt;\n");
		self.line("#[cfg(feature = \"kotlin\")]\nmod jni;\n");
		self.line("#[cfg(feature = \"python\")]\nmod python;\n");
		self.line("#[cfg(feature = \"dart\")]\nmod dart;\n");
		// The facade may export nothing, which cargo would call unused.
		self.line(format!("use {} as _;\n", self.dependency));

		let p = self.abi.prefix.clone();
		self.line(format!(
			"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {p}_buf_free(buf: rt::Buf) {{\n\tunsafe {{ buf.free() }}\n}}\n"
		));
		self.line(format!(
			"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {p}_buf_copy(view: rt::Buf) -> rt::Buf {{\n\trt::Buf::vec(unsafe {{ view.bytes(\"{p}_buf_copy\") }}.to_vec())\n}}\n"
		));
		self.line(format!(
			"#[unsafe(no_mangle)]\npub extern \"C\" fn {p}_contract() -> u64 {{\n\t0x{:016x}\n}}\n",
			self.contract
		));
		// Its index among the targets the header serves, by which a binding checks a call of
		// an item only some have before making it.
		for (i, target) in api.targets.iter().enumerate() {
			self.line(format!("#[cfg({CFG} = {target:?})]\nconst TARGET: u32 = {i};\n"));
		}
		self.line(format!(
			"#[unsafe(no_mangle)]\npub extern \"C\" fn {p}_target() -> u32 {{\n\tTARGET\n}}\n"
		));

		for (name, ty) in &self.abi.ranges {
			let (kind, int) = match ty {
				Type::Range(int) => ("Range", int),
				Type::Bound(int) => ("Bound", int),
				Type::Bounds(int) => ("Bounds", int),
				other => unreachable!("{other:?} is no range"),
			};
			self.line(format!("pub type {name} = rt::{kind}<{}>;\n", int.rust()));
		}
		for (name, elem) in &self.abi.lists.clone() {
			let c = rs(&self.abi.ty(elem));
			self.line(format!("pub type {name} = rt::List<{c}>;\n"));
			self.on = self.abi.on(elem);
			let free = self
				.free(&Type::List(Collection::Vec, Box::new(elem.clone())), "this")
				.expect("an array is freed");
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_free(this: {name}) {{\n\t{free}\n}}\n"
			));
		}
		for (name, n) in &self.abi.arrays {
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n\tpub items: [u8; {n}],\n}}\n"
			));
		}
		for (name, elements) in &self.abi.tuples.clone() {
			let fields: String = (elements.iter().enumerate())
				.map(|(n, ty)| format!("\tpub _{n}: {},\n", rs(&self.abi.ty(ty))))
				.collect();
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n{fields}}}\n"
			));
		}
		for (name, inner) in &self.abi.options.clone() {
			let value = rs(&self.abi.ty(inner));
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n\tpub some: bool,\n\tpub value: {value},\n}}\n"
			));
		}
		for i in 0..api.records.len() {
			self.record(i);
		}
		for i in 0..api.enums.len() {
			self.enumeration(i);
		}
		for i in 0..api.callbacks.len() {
			self.callback(i);
		}
		for (i, object) in api.objects.iter().enumerate() {
			self.on = object.on;
			let name = self.abi.object(i);
			let path = self.object_path(i);
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_free(this: *const ::std::ffi::c_void) {{\n\tunsafe {{ rt::Object::<{path}>::free(this) }}\n}}\n"
			));
			if object.shared {
				self.export(format!(
					"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_borrowed(this: *const ::std::ffi::c_void) -> bool {{\n\tunsafe {{ rt::Object::<{path}>::borrowed(this, \"{name}_borrowed\") }}\n}}\n"
				));
			}
			let borrow = self.shared(i);
			self.traits(&name, &path, object.traits, |e| {
				format!("unsafe {{ rt::Object::<{path}>::{borrow}({e}, w) }}")
			});
			if self.abi.copies.contains(&i) {
				self.export(format!(
					"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_copy(this: *const ::std::ffi::c_void) -> *const ::std::ffi::c_void {{\n\tlet w = \"{name}_copy\";\n\trt::Object::new(*unsafe {{ rt::Object::<{path}>::{borrow}(this, w) }})\n}}\n"
				));
			}
			let owner = Ty::Handle {
				name: name.clone(),
				constant: false,
			};
			for method in &object.methods {
				self.function(method, Some((&owner, Type::Object(i))));
			}
		}
		for function in &api.functions {
			self.function(function, None);
		}
	}

	/// The functions a type's std traits export; `borrow` reads the receiver `e`.
	fn traits(&mut self, name: &str, path: &str, traits: Traits, borrow: impl Fn(&str) -> String) {
		let handle = "*const ::std::ffi::c_void";
		if traits.clone {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_clone(this: {handle}) -> {handle} {{\n\tlet w = \"{name}_clone\";\n\tlet this = {};\n\trt::Object::new(<{path} as ::std::clone::Clone>::clone(&*this))\n}}\n",
				borrow("this")
			));
		}
		if traits.eq {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_eq(a: {handle}, b: {handle}) -> bool {{\n\tlet w = \"{name}_eq\";\n\tlet a = {};\n\tlet b = {};\n\t<{path} as ::std::cmp::PartialEq>::eq(&*a, &*b)\n}}\n",
				borrow("a"),
				borrow("b")
			));
		}
		if traits.display {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_to_string(this: {handle}) -> rt::Buf {{\n\tlet w = \"{name}_to_string\";\n\tlet this = {};\n\trt::Buf::string(::std::string::ToString::to_string(&*this))\n}}\n",
				borrow("this")
			));
		}
		if traits.debug {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_debug(this: {handle}) -> rt::Buf {{\n\tlet w = \"{name}_debug\";\n\tlet this = {};\n\trt::Buf::string(format!(\"{{:?}}\", &*this))\n}}\n",
				borrow("this")
			));
		}
		if traits.default {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_default() -> {handle} {{\n\trt::Object::new(<{path} as ::std::default::Default>::default())\n}}\n"
			));
		}
	}

	/// The functions every value type has: its std traits, read through a pointer, and
	/// `free`.
	fn value_traits(&mut self, name: &str, path: &str, ty: &Type, traits: Traits) {
		let lift = self.lift(ty, "unsafe { *this }");
		let lift_a = self.lift(ty, "unsafe { *a }");
		let lift_b = self.lift(ty, "unsafe { *b }");
		let c = rs(&self.abi.ty(ty));
		if traits.eq {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_eq(a: *const {c}, b: *const {c}) -> bool {{\n\tlet w = \"{name}_eq\";\n\t<{path} as ::std::cmp::PartialEq>::eq(&{lift_a}, &{lift_b})\n}}\n"
			));
		}
		if traits.display {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_to_string(this: *const {c}) -> rt::Buf {{\n\tlet w = \"{name}_to_string\";\n\trt::Buf::string(::std::string::ToString::to_string(&{lift}))\n}}\n"
			));
		}
		if traits.debug {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_debug(this: *const {c}) -> rt::Buf {{\n\tlet w = \"{name}_debug\";\n\trt::Buf::string(format!(\"{{:?}}\", &{lift}))\n}}\n"
			));
		}
		if traits.default {
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_default() -> {c} {{\n\t{}\n}}\n",
				self.lower(ty, &format!("<{path} as ::std::default::Default>::default()"))
			));
		}
		if !matches!(self.abi.ty(ty), Ty::Enum(_)) {
			let free = self.free(ty, "unsafe { this.read() }").unwrap_or_default();
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}_free(this: *mut {c}) {{\n\tif this.is_null() {{\n\t\treturn;\n\t}}\n\t{free}\n}}\n"
			));
		}
	}

	fn record(&mut self, i: usize) {
		let record = &self.abi.api.records[i];
		self.on = record.on;
		let name = self.abi.record(i);
		let path = self.rust(&Type::Record(i));
		let ty = Type::Record(i);
		let mut fields = String::new();
		for (n, field) in record.fields.iter().enumerate() {
			let _ = writeln!(fields, "\tpub f{n}: {},", rs(&self.abi.ty(&field.ty)));
		}
		self.line(format!(
			"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n{fields}}}\n"
		));
		let lifted: Vec<String> = record
			.fields
			.iter()
			.enumerate()
			.map(|(n, f)| self.lift(&f.ty, &format!("c.f{n}")))
			.collect();
		let build = match record.tuple {
			true => format!("{path}({})", lifted.join(", ")),
			false => {
				let fields: Vec<String> = record
					.fields
					.iter()
					.zip(&lifted)
					.map(|(f, l)| format!("{}: {l}", f.name))
					.collect();
				format!("{path} {{ {} }}", fields.join(", "))
			}
		};
		self.item(format!(
			"fn lift_{name}(c: &{name}, w: &str) -> {path} {{\n\tlet _ = w;\n\t{build}\n}}\n"
		));
		let bindings: Vec<String> = (0..record.fields.len()).map(|n| format!("f{n}")).collect();
		let pattern = match record.tuple {
			true => format!("{path}({})", bindings.join(", ")),
			false => {
				let fields: Vec<String> = record
					.fields
					.iter()
					.zip(&bindings)
					.map(|(f, b)| format!("{}: {b}", f.name))
					.collect();
				format!("{path} {{ {} }}", fields.join(", "))
			}
		};
		let lowered: Vec<String> = record
			.fields
			.iter()
			.enumerate()
			.map(|(n, f)| format!("f{n}: {}", self.lower(&f.ty, &format!("f{n}"))))
			.collect();
		self.item(format!(
			"fn lower_{name}(v: {path}) -> {name} {{\n\tlet {pattern} = v;\n\t{name} {{ {} }}\n}}\n",
			lowered.join(", ")
		));
		if self.owns(&ty) {
			let frees: Vec<String> = record
				.fields
				.iter()
				.enumerate()
				.filter_map(|(n, f)| self.free(&f.ty, &format!("c.f{n}")))
				.collect();
			self.item(format!("fn free_{name}(c: {name}) {{\n\t{}\n}}\n", frees.join("\n\t")));
		}
		self.value_traits(&name, &path, &ty, record.traits);
		let owner = Ty::Struct(name.clone());
		for method in &record.methods {
			self.function(method, Some((&owner, ty.clone())));
		}
	}

	fn enumeration(&mut self, i: usize) {
		let e = &self.abi.api.enums[i];
		self.on = e.on;
		let name = self.abi.enumeration(i);
		let path = self.rust(&Type::Enum(i));
		let ty = Type::Enum(i);
		let wildcard = match e.exhaustive {
			true => "",
			false => "\n\t\t_ => unreachable!(\"a variant this export does not know\"),",
		};
		// A foreign enum's variants are its type's constants.
		let variant = |v: &crate::ir::Variant| match e.foreign {
			true => abi::snake(&v.name).to_uppercase(),
			false => v.name.clone(),
		};
		if e.plain() {
			let lift: Vec<String> = (e.variants.iter())
				.map(|v| {
					let missing = self.cfg(v.on).map(|cfg| {
						format!(
							"\n\t\t#[cfg(not({cfg}))]\n\t\t{} => rt::fail(w, \"the variant is not on this library's target\"),",
							v.discriminant
						)
					});
					let arm = self.arm(v.on);
					format!(
						"{arm}\n\t\t{} => {path}::{},{}",
						v.discriminant,
						variant(v),
						missing.unwrap_or_default()
					)
				})
				.collect();
			let lower: Vec<String> = (e.variants.iter())
				.map(|v| format!("{}\n\t\t{path}::{} => {},", self.arm(v.on), variant(v), v.discriminant))
				.collect();
			self.item(format!(
				"fn lift_{name}(c: i32, w: &str) -> {path} {{\n\tmatch c {{{}\n\t\t_ => rt::fail(w, \"an enum value is invalid\"),\n\t}}\n}}\n",
				lift.concat()
			));
			self.item(format!(
				"fn lower_{name}(v: {path}) -> i32 {{\n\tmatch v {{{}{wildcard}\n\t}}\n}}\n",
				lower.concat()
			));
		} else {
			let mut members = String::new();
			for (n, variant) in e.variants.iter().enumerate().filter(|(_, v)| !v.fields.is_empty()) {
				let payload = abi::payload(&name, &variant.name);
				let mut fields = String::new();
				for (k, field) in variant.fields.iter().enumerate() {
					let _ = writeln!(fields, "\tpub f{k}: {},", rs(&self.abi.ty(&field.ty)));
				}
				self.line(format!(
					"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {payload} {{\n{fields}}}\n"
				));
				let _ = writeln!(members, "\tpub v{n}: {payload},");
			}
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub union {name}_union {{\n{members}}}\n"
			));
			self.line(format!(
				"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n\tpub tag: i32,\n\tpub u: {name}_union,\n}}\n"
			));
			let mut lift = String::new();
			let mut lower = String::new();
			let mut free = String::new();
			for (n, variant) in e.variants.iter().enumerate() {
				let bindings: Vec<String> = (0..variant.fields.len()).map(|k| format!("f{k}")).collect();
				let pattern = match (variant.fields.is_empty(), variant.tuple) {
					(true, _) => format!("{path}::{}", variant.name),
					(false, true) => format!("{path}::{}({})", variant.name, bindings.join(", ")),
					(false, false) => {
						let fields: Vec<String> = variant
							.fields
							.iter()
							.zip(&bindings)
							.map(|(f, b)| format!("{}: {b}", f.name))
							.collect();
						format!("{path}::{} {{ {} }}", variant.name, fields.join(", "))
					}
				};
				let arm = self.arm(variant.on);
				if let Some(cfg) = self.cfg(variant.on) {
					let _ = write!(
						lift,
						"\n\t\t#[cfg(not({cfg}))]\n\t\t{n} => rt::fail(w, \"the variant is not on this library's target\"),"
					);
				}
				if variant.fields.is_empty() {
					let _ = write!(lift, "{arm}\n\t\t{n} => {pattern},");
					let _ = write!(
						lower,
						"{arm}\n\t\t{pattern} => {name} {{ tag: {n}, u: unsafe {{ ::std::mem::zeroed() }} }},"
					);
					continue;
				}
				let payload = abi::payload(&name, &variant.name);
				let lifted: Vec<String> = variant
					.fields
					.iter()
					.enumerate()
					.map(|(k, f)| self.lift(&f.ty, &format!("p.f{k}")))
					.collect();
				let build = match variant.tuple {
					true => format!("{path}::{}({})", variant.name, lifted.join(", ")),
					false => {
						let fields: Vec<String> = variant
							.fields
							.iter()
							.zip(&lifted)
							.map(|(f, l)| format!("{}: {l}", f.name))
							.collect();
						format!("{path}::{} {{ {} }}", variant.name, fields.join(", "))
					}
				};
				let _ = write!(
					lift,
					"{arm}\n\t\t{n} => {{\n\t\t\tlet p = unsafe {{ c.u.v{n} }};\n\t\t\t{build}\n\t\t}}"
				);
				let lowered: Vec<String> = variant
					.fields
					.iter()
					.enumerate()
					.map(|(k, f)| format!("f{k}: {}", self.lower(&f.ty, &format!("f{k}"))))
					.collect();
				let _ = write!(
					lower,
					"{arm}\n\t\t{pattern} => {name} {{ tag: {n}, u: {name}_union {{ v{n}: {payload} {{ {} }} }} }},",
					lowered.join(", ")
				);
				let frees: Vec<String> = variant
					.fields
					.iter()
					.enumerate()
					.filter_map(|(k, f)| self.free(&f.ty, &format!("p.f{k}")))
					.collect();
				if !frees.is_empty() {
					let _ = write!(
						free,
						"{arm}\n\t\t{n} => {{\n\t\t\tlet p = unsafe {{ c.u.v{n} }};\n\t\t\t{}\n\t\t}}",
						frees.join("\n\t\t\t")
					);
				}
			}
			self.item(format!(
				"fn lift_{name}(c: &{name}, w: &str) -> {path} {{\n\tmatch c.tag {{{lift}\n\t\t_ => rt::fail(w, \"an enum tag is invalid\"),\n\t}}\n}}\n"
			));
			self.item(format!(
				"fn lower_{name}(v: {path}) -> {name} {{\n\tmatch v {{{lower}{wildcard}\n\t}}\n}}\n"
			));
			if self.owns(&ty) {
				self.item(format!(
					"fn free_{name}(c: {name}) {{\n\tmatch c.tag {{{free}\n\t\t_ => {{}}\n\t}}\n}}\n"
				));
			}
		}
		self.value_traits(&name, &path, &ty, e.traits);
		let owner = self.abi.ty(&ty);
		for method in &e.methods {
			self.function(method, Some((&owner, ty.clone())));
		}
	}

	/// A callback: its table of foreign functions, and the Rust type that implements the
	/// trait by calling them.
	fn callback(&mut self, i: usize) {
		let callback = &self.abi.api.callbacks[i];
		self.on = callback.on;
		let name = self.abi.callback(i);
		let path = self.path(&callback.path);
		let mut table = String::from("\tpub free: Option<unsafe extern \"C\" fn(*mut ::std::ffi::c_void)>,\n");
		let mut methods = String::new();
		for method in &callback.methods {
			let method_name = method.name();
			let c_params: Vec<String> = std::iter::once("*mut ::std::ffi::c_void".to_string())
				.chain(method.params.iter().map(|p| rs(&self.abi.ty(&p.ty))))
				.collect();
			let ret = rs(&self.abi.ty(&method.ok));
			let _ = writeln!(
				table,
				"\tpub {method_name}: Option<unsafe extern \"C\" fn({}) -> {ret}>,",
				c_params.join(", ")
			);
			let receiver = match method.receiver {
				Some(Receiver::Mut) => "&mut self",
				_ => "&self",
			};
			let params: Vec<String> = method
				.params
				.iter()
				.enumerate()
				.map(|(n, p)| format!("p{n}: {}", self.rust(&p.ty)))
				.collect();
			let args: Vec<String> = std::iter::once("self.0.data".to_string())
				.chain(
					method
						.params
						.iter()
						.enumerate()
						.map(|(n, p)| self.view(&p.ty, &format!("p{n}"))),
				)
				.collect();
			let _ = write!(
				methods,
				"\tfn {method_name}({receiver}{}) -> {} {{\n\t\tlet w = \"{name}_vtable.{method_name}\";\n\t\tlet f = unsafe {{ (*self.0.vtable).{method_name} }}.unwrap_or_else(|| rt::fail(w, \"the function is null\"));\n\t\tlet result = unsafe {{ f({}) }};\n\t\t{}\n\t}}\n",
				params.iter().map(|p| format!(", {p}")).collect::<String>(),
				self.rust(&method.ok),
				args.join(", "),
				self.lift(&method.ok, "result"),
			);
		}
		self.line(format!("#[repr(C)]\npub struct {name}_vtable {{\n{table}}}\n"));
		self.line(format!(
			"#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {name} {{\n\tpub vtable: *const {name}_vtable,\n\tpub data: *mut ::std::ffi::c_void,\n}}\n"
		));
		// Each item apart, as each takes the target's `#[cfg]`.
		self.item(format!(
			"/// The foreign implementation, which frees its data when dropped.\npub struct Foreign_{name}({name});\n"
		));
		self.item(format!(
			"// SAFETY: the callback's contract: its functions may be called from any thread.\nunsafe impl Send for Foreign_{name} {{}}\n"
		));
		self.item(format!(
			"// SAFETY: as above.\nunsafe impl Sync for Foreign_{name} {{}}\n"
		));
		self.item(format!(
			"impl Drop for Foreign_{name} {{\n\tfn drop(&mut self) {{\n\t\tif let Some(free) = unsafe {{ (*self.0.vtable).free }} {{\n\t\t\tunsafe {{ free(self.0.data) }};\n\t\t}}\n\t}}\n}}\n"
		));
		self.item(format!("impl {path} for Foreign_{name} {{\n{methods}}}\n"));
	}

	/// The C value lending the Rust value `e` of type `ty` to a callback for its call.
	fn view(&self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Ref(_, inner) => match &**inner {
				Type::Str => format!("rt::Buf::view({e}.as_bytes())"),
				Type::Path => format!("rt::Buf::view({e}.as_os_str().as_encoded_bytes())"),
				_ => format!("rt::Buf::view({e})"),
			},
			Type::String => format!("rt::Buf::view({e}.as_bytes())"),
			Type::Vec | Type::Bytes => format!("rt::Buf::view(&{e}[..])"),
			Type::PathBuf => format!("rt::Buf::view({e}.as_os_str().as_encoded_bytes())"),
			Type::Option(inner) => match &**inner {
				inner if Abi::is_buf(inner) => format!(
					"match &{e} {{ Some(v) => {}, None => rt::Buf::NONE }}",
					self.view(inner, "v")
				),
				inner => format!(
					"match {e} {{ Some(v) => {name} {{ some: true, value: {} }}, None => {name} {{ some: false, value: unsafe {{ ::std::mem::zeroed() }} }} }}",
					self.view(inner, "v"),
					name = self.abi.option(inner)
				),
			},
			_ => self.lower(ty, e),
		}
	}

	/// An argument: the statement binding it from its C parameter `c` to `local`, and
	/// the expression passing it. A future owns its arguments, so it borrows nothing
	/// from the caller.
	fn arg(&self, ty: &Type, c: &str, local: &str, future: bool) -> (String, String) {
		match ty {
			Type::Ref(m, inner) => match (&**inner, m, future) {
				(Type::Object(i), _, _) => {
					let (binding, borrow) = self.borrow(*i, *m, c, future);
					let pass = match (m, self.abi.api.objects[*i].opaque) {
						(Mutability::Not, true) => format!("{local}.get(w)"),
						(Mutability::Mut, _) => format!("&mut *{local}"),
						(Mutability::Not, false) => format!("&*{local}"),
					};
					(format!("{binding} {local} = {borrow};"), pass)
				}
				(Type::Str, Mutability::Not, false) => {
					(format!("let {local} = unsafe {{ {c}.str(w) }};"), local.to_string())
				}
				(Type::Slice, Mutability::Not, false) => {
					(format!("let {local} = unsafe {{ {c}.bytes(w) }};"), local.to_string())
				}
				(Type::Path, Mutability::Not, false) => {
					(format!("let {local} = unsafe {{ {c}.path(w) }};"), local.to_string())
				}
				(inner, m, _) => {
					let (binding, pass) = match m {
						Mutability::Mut => ("let mut", format!("&mut {local}")),
						Mutability::Not => ("let", format!("&{local}")),
					};
					(format!("{binding} {local} = {};", self.lift(inner, c)), pass)
				}
			},
			// `Some` of a borrow, lent as the borrow alone is: a null handle or buffer is `None`.
			Type::Option(opt) if let Type::Ref(m, inner) = &**opt => match (&**inner, future) {
				(Type::Object(i), _) => {
					let (binding, borrow) = self.borrow(*i, *m, c, future);
					let pass = match (m, self.abi.api.objects[*i].opaque) {
						(Mutability::Not, true) => format!("{local}.as_deref().map(|v| v.get(w))"),
						(Mutability::Mut, _) => format!("{local}.as_deref_mut()"),
						(Mutability::Not, false) => format!("{local}.as_deref()"),
					};
					(
						format!("{binding} {local} = if {c}.is_null() {{ None }} else {{ Some({borrow}) }};"),
						pass,
					)
				}
				(Type::Str | Type::Slice | Type::Path, false) => {
					let view = match &**inner {
						Type::Str => "str",
						Type::Slice => "bytes",
						_ => "path",
					};
					(
						format!(
							"let {local} = if {c}.is_none() {{ None }} else {{ Some(unsafe {{ {c}.{view}(w) }}) }};"
						),
						local.to_string(),
					)
				}
				// A future owns its arguments, so it lends a buffer's owned form.
				(Type::Str | Type::Slice | Type::Path, true) => (
					format!("let {local} = {};", self.lift(ty, c)),
					format!("{local}.as_deref()"),
				),
				_ => (
					format!("let {local} = {};", self.lift(ty, c)),
					format!("{local}.as_ref()"),
				),
			},
			_ => (format!("let {local} = {};", self.lift(ty, c)), local.to_string()),
		}
	}

	/// The binding and expression borrowing object `i`'s handle `c` as `m` does. A future
	/// may be polled on any thread, so it holds a value that is not `Sync` exclusively.
	fn borrow(&self, i: usize, m: Mutability, c: &str, future: bool) -> (&'static str, String) {
		let exclusive = m == Mutability::Mut || (future && !self.abi.api.objects[i].sync);
		let borrow = match (exclusive, future) {
			(false, false) => self.shared(i),
			(true, false) => "borrow_mut",
			(false, true) => "borrow_arc",
			(true, true) => "borrow_mut_arc",
		};
		let binding = match exclusive {
			true => "let mut",
			false => "let",
		};
		(
			binding,
			format!("unsafe {{ rt::Object::<{}>::{borrow}({c}, w) }}", self.object_path(i)),
		)
	}

	/// The out pointers a call's value is written through: one per element of a tuple.
	fn outs(function: &Function) -> Vec<String> {
		match &function.ok {
			Type::Unit => Vec::new(),
			Type::Tuple(elements) => (0..elements.len()).map(|n| format!("out{n}")).collect(),
			_ => vec!["out".to_string()],
		}
	}

	/// The statements that hand a call's `result` to C: return it, or for a fallible
	/// function or a tuple, write it through its out pointers or `err`, and return whether
	/// it succeeded.
	fn finish(&self, function: &Function, ok: &Type, ret: (&str, &str, &str)) -> String {
		let (ok_value, ready, error) = ret;
		let write = |ty: &Type, out: &str, v: &str| {
			format!(
				"unsafe {{ rt::write::<{}>({out}.cast(), || {}) }};",
				rs(&self.abi.ty(ty)),
				self.lower(ty, v)
			)
		};
		// The outs C passes follow what the function returns, which `ok` may own.
		let write_ok = match (&function.ok, ok) {
			(_, Type::Unit) => String::new(),
			(Type::Tuple(_), Type::Tuple(elements)) => {
				let names: Vec<String> = (0..elements.len()).map(|n| format!("v{n}")).collect();
				let writes: Vec<String> = elements
					.iter()
					.zip(Self::outs(function))
					.zip(&names)
					.map(|((ty, out), v)| write(ty, &out, v))
					.collect();
				// The trailing comma makes `(v0,)` a tuple pattern, not parentheses.
				format!("let ({},) = v;\n\t{}", names.join(", "), writes.join("\n\t"))
			}
			(_, ok) => write(ok, "out", "v"),
		};
		match &function.err {
			None if ok_value.is_empty() => match (&function.ok, ok) {
				(_, Type::Unit) => "result".to_string(),
				(Type::Tuple(_), _) => format!("let v = result;\n\t{write_ok}"),
				_ => self.lower(ok, "result"),
			},
			None => match ok {
				Type::Unit => format!("let _ = result;\n\t{ready}"),
				_ => format!("let v = result;\n\t{write_ok}\n\t{ready}"),
			},
			Some(err) => format!(
				"match result {{\n\t\tOk(v) => {{\n\t\t\tlet _ = &v;\n\t\t\t{write_ok}\n\t\t\t{ready}\n\t\t}}\n\t\tErr(e) => {{\n\t\t\tunsafe {{ rt::write::<{}>(err.cast(), || {}) }};\n\t\t\t{error}\n\t\t}}\n\t}}",
				rs(&self.abi.ty(err)),
				match err {
					// A `String` error may stand for another crate's, as its message.
					Type::String => self.lower(err, "::std::string::ToString::to_string(&e)"),
					err => self.lower(err, "e"),
				}
			),
		}
	}

	/// An exported function, a method of `owner` if it has one: its C type, and its type.
	fn function(&mut self, function: &Function, owner: Option<(&Ty, Type)>) {
		let on = std::mem::replace(&mut self.on, function.on);
		self.function_on(function, owner);
		self.on = on;
	}

	fn function_on(&mut self, function: &Function, owner: Option<(&Ty, Type)>) {
		let export = self.abi.export(function, owner.as_ref().map(|(ty, _)| *ty));
		let name = export.call.name.clone();
		// An eager call borrows its arguments only for the call, as a synchronous one does.
		let future = function.future && !function.eager;
		let mut stmts = Vec::new();
		let mut args = Vec::new();
		let mut params = Vec::new();
		let mut c_params = export.call.params.iter();
		let receiver_ty = owner.as_ref().zip(function.receiver);
		if let Some(((_, owner_type), receiver)) = &receiver_ty {
			let (_, c_ty) = c_params.next().expect("a method takes self");
			params.push(format!("this: {}", rs(c_ty)));
			match owner_type {
				Type::Object(i) => {
					let ty = match receiver {
						Receiver::Ref => Type::Ref(Mutability::Not, Box::new(Type::Object(*i))),
						Receiver::Mut => Type::Ref(Mutability::Mut, Box::new(Type::Object(*i))),
						Receiver::Owned => Type::Object(*i),
					};
					let (stmt, arg) = self.arg(&ty, "this", "a_self", future);
					stmts.push(stmt);
					args.push(arg);
				}
				value => {
					stmts.push(format!("let a_self = {};", self.lift(value, "unsafe { *this }")));
					args.push(match receiver {
						Receiver::Owned => "a_self".to_string(),
						_ => "&a_self".to_string(),
					});
				}
			}
		}
		// Each parameter's place among Rust's after `self`, past the `()` ones C does not
		// pass and a future's context, which is the poll's.
		let omitted = |at: &usize| {
			function.units.contains(at)
				|| (function.future && function.task.as_ref().is_some_and(|task| task.at == *at))
		};
		let mut places = (0..).filter(|at| !omitted(at));
		for (n, param) in function.params.iter().enumerate() {
			let place = places.next().expect("a place for each parameter");
			let (_, c_ty) = c_params.next().expect("a C parameter for each");
			params.push(format!("p{n}: {}", rs(c_ty)));
			if let Type::Closure(closure) = &param.ty {
				let (_, data) = c_params.next().expect("a lent function's data");
				params.push(format!("p{n}_data: {}", rs(data)));
				if closure.kept {
					let (_, free) = c_params.next().expect("a kept function's free");
					params.push(format!("p{n}_free: {}", rs(free)));
				}
			}
			let (stmt, arg) = match &function.task {
				// A context made of C's waker, lent for the call.
				Some(Task {
					at,
					kind: TaskKind::Context(m),
				}) if *at == place && !function.future => {
					let (binding, pass) = match m {
						Mutability::Mut => ("let mut", format!("&mut a{n}")),
						Mutability::Not => ("let", format!("&a{n}")),
					};
					(
						format!(
							"let a{n}_waker = p{n}.lift();\n\t{binding} a{n} = ::std::task::Context::from_waker(&a{n}_waker);"
						),
						pass,
					)
				}
				_ if param.interned => (
					format!("let a{n} = rt::intern(unsafe {{ p{n}.str(w) }});"),
					format!("a{n}"),
				),
				// A future made of a `Poll` owns a future C implements, and lends it pinned to
				// each poll.
				Some(_) if function.future && param.ty == Type::Future => (
					format!("let mut a{n} = p{n}.lift(w);"),
					format!("::std::pin::Pin::new(&mut a{n})"),
				),
				_ => self.arg(&param.ty, &format!("p{n}"), &format!("a{n}"), future),
			};
			stmts.push(stmt);
			args.push(arg);
		}
		// A future made of a `Poll` calls the function at each poll, passing the poll's
		// context, or a value made from its waker and kept until the next poll, so what that
		// poll registers stays registered.
		let mut made = String::new();
		// Each argument C does not pass, by its place among Rust's parameters after `self`,
		// inserted in order so each lands where Rust takes it.
		let mut extra: Vec<(usize, String)> = function.units.iter().map(|&at| (at, "()".to_string())).collect();
		if let Some(task) = function.task.as_ref().filter(|_| function.future) {
			let pass = match &task.kind {
				TaskKind::Context(Mutability::Mut) => "&mut *t_cx".to_string(),
				TaskKind::Context(Mutability::Not) => "&*t_cx".to_string(),
				TaskKind::Made { object, make } => {
					made = format!(
						"let t_made = t_held.insert(<{}>::{make}(::std::task::Context::waker(t_cx).clone()));\n\t\t\t",
						self.object_path(*object)
					);
					"&*t_made".to_string()
				}
			};
			extra.push((task.at, pass));
		}
		extra.sort_by_key(|(at, _)| *at);
		for (at, arg) in extra {
			args.insert(usize::from(receiver_ty.is_some()) + at, arg);
		}
		// Rust writes back what the call left in each value C passed for `&mut`, on every
		// path, errors included.
		let writes: String = (function.params.iter().enumerate())
			.filter(|(_, param)| param.ty.written())
			.map(|(n, param)| {
				let Type::Ref(_, inner) = &param.ty else {
					unreachable!("a written parameter is `&mut`")
				};
				let out = Abi::written(function, &crate::abi::escape(&param.name));
				format!(
					"\n\tunsafe {{ rt::write::<{}>({out}.cast(), || {}) }};",
					rs(&self.abi.ty(inner)),
					self.lower(inner, &format!("a{n}"))
				)
			})
			.collect();
		let mut callee = match &owner {
			Some((_, owner_type)) => format!("<{}>::{}", self.rust(owner_type), function.name()),
			None => self.path(&function.path),
		};
		if let Some(instance) = function.instance.as_ref().filter(|i| !i.args.is_empty()) {
			let args: Vec<String> = (instance.args.iter())
				.map(|ty| ty.as_ref().map_or_else(|| "_".to_string(), |ty| self.rust(ty)))
				.collect();
			callee = format!("{callee}::<{}>", args.join(", "));
		}
		let call = match function.access {
			Access::Call => format!("{callee}({})", args.join(", ")),
			Access::Field { set: false, .. } => format!("&({}).{}", args[0], function.name()),
			Access::Field { set: true, .. } => format!("({}).{} = {}", args[0], function.name(), args[1]),
			Access::Const => callee,
			Access::Parse => format!(
				"<{} as ::std::str::FromStr>::from_str({}).map_err(|e| ::std::string::ToString::to_string(&e))",
				self.rust(&owner.as_ref().expect("a parse has its type").1),
				args[0]
			),
			Access::Text => format!("::std::string::ToString::to_string({})", args[0]),
		};
		if function.lends {
			let Some((_, Type::Object(i))) = &owner else {
				unreachable!("a lent return is a method of an object's")
			};
			let lender = match self.abi.api.objects[*i].sync {
				true => "lender",
				false => "lender_local",
			};
			stmts.push(format!(
				"let lender = unsafe {{ rt::Object::<{}>::{lender}(this, w) }};",
				self.object_path(*i)
			));
		}
		let body = stmts.join("\n\t");
		if let Some(abi::Future { start, poll, free, .. }) = &export.future {
			// A function that is not `async` runs when called, and what it returns
			// borrows nothing, so it is called now; an `async fn` runs when polled.
			let (now, later) = match (function.eager, &function.task) {
				(true, _) => (format!("\n\tlet future = {call};"), "future".to_string()),
				(false, None) => (String::new(), call),
				(false, Some(task)) => {
					let held = match task.kind {
						TaskKind::Made { .. } => "let mut t_held = None;\n\t\t",
						TaskKind::Context(_) => "",
					};
					(
						String::new(),
						format!(
							"{{\n\t\t{held}::std::future::poll_fn(move |t_cx: &mut ::std::task::Context<'_>| {{\n\t\t\t{made}{call}\n\t\t}})\n\t\t}}"
						),
					)
				}
			};
			// The value C takes is lowered when it polls, outside the future, so a result
			// borrowing what the future holds is cloned before the future ends.
			let (ok, own) = owned(&function.ok);
			let later = match (own, &function.err) {
				(None, _) => format!("{later}.await"),
				(Some(own), Some(_)) => format!("{later}.await.map(|v| {own})"),
				(Some(own), None) => format!("{{ let v = {later}.await; {own} }}"),
			};
			let bind: String = Self::outs(function)
				.iter()
				.enumerate()
				.map(|(n, out)| format!("let {out} = outs[{n}];\n\t\t\t"))
				.collect();
			// The make's body, emitted again inside `<fn>_start` so its aborts name the
			// function C called.
			let make = format!(
				"{body}{now}\n\trt::Future::new(async move {{ {later} }}, move |result, outs: &[*mut ::std::ffi::c_void], err: *mut ::std::ffi::c_void| -> i32 {{\n\t\tlet _ = (outs, err);\n\t\t{bind}{}\n\t}})",
				self.finish(function, &ok, ("v", "rt::READY", "rt::ERROR"))
			);
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({}) -> *mut rt::Future {{\n\tlet w = \"{name}\";\n\tlet _ = w;\n\t{make}\n}}\n",
				params.join(", "),
			));
			let poll_params: Vec<String> = poll.params[2..]
				.iter()
				.map(|(n, ty)| format!("{n}: {}", rs(ty)))
				.collect();
			let outs: Vec<String> = Self::outs(function).iter().map(|out| format!("{out}.cast()")).collect();
			let outs = outs.join(", ");
			let err = match function.err {
				Some(_) => "err.cast()",
				None => "::std::ptr::null_mut()",
			};
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(future: *mut rt::Future, waker: rt::Waker{}) -> i32 {{\n\tunsafe {{ rt::Future::poll(future, waker, &[{outs}], {err}, \"{}\") }}\n}}\n",
				poll.name,
				poll_params.iter().map(|p| format!(", {p}")).collect::<String>(),
				poll.name
			));
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}(future: *mut rt::Future) {{\n\tunsafe {{ rt::Future::free(future) }}\n}}\n",
				free.name
			));
			// The call and its first poll in one: most futures are ready at once.
			let start_params: Vec<String> = (params.iter().cloned())
				.chain(poll_params)
				.chain(["future: *mut *mut rt::Future".to_string()])
				.collect();
			self.export(format!(
				"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {}({}) -> i32 {{\n\tlet w = \"{}\";\n\tlet _ = w;\n\tlet made = {{\n\t{make}\n\t}};\n\tunsafe {{ rt::Future::start(made, &[{outs}], {err}, future, w) }}\n}}\n",
				start.name,
				start_params.join(", "),
				start.name
			));
			return;
		}
		let outs: Vec<String> = export.call.params[params.len()..]
			.iter()
			.map(|(n, ty)| format!("{n}: {}", rs(ty)))
			.collect();
		params.extend(outs);
		let ret = rs(&export.call.ret);
		self.lends = function.lends;
		let finish = match function.err {
			Some(_) => self.finish(function, &function.ok, ("v", "true", "false")),
			None => self.finish(function, &function.ok, ("", "", "")),
		};
		self.lends = false;
		self.export(format!(
			"#[unsafe(no_mangle)]\npub unsafe extern \"C\" fn {name}({}) -> {ret} {{\n\tlet w = \"{name}\";\n\tlet _ = w;\n\t{body}\n\tlet result = {};{writes}\n\t{finish}\n}}\n",
			params.join(", "),
			match function.collect {
				// An iterator's items, all taken now.
				true => format!("::std::iter::Iterator::collect::<::std::vec::Vec<_>>({call})"),
				false => call,
			},
		));
	}
}

/// What a function returns, owned: each reference at its top or in a returned tuple as
/// its clone's type, with the expression cloning `v` into it, if any is one.
fn owned(ok: &Type) -> (Type, Option<String>) {
	let one = |ty: &Type| match ty {
		Type::Ref(_, inner) => Some(match &**inner {
			Type::Str => Type::String,
			Type::Slice => Type::Vec,
			Type::Path => Type::PathBuf,
			inner => inner.clone(),
		}),
		_ => None,
	};
	match ok {
		Type::Tuple(elements) if elements.iter().any(|e| one(e).is_some()) => {
			let names: Vec<String> = (0..elements.len()).map(|n| format!("v{n}")).collect();
			let owned: Vec<String> = (elements.iter().zip(&names))
				.map(|(e, n)| match one(e) {
					Some(_) => format!("::std::borrow::ToOwned::to_owned({n})"),
					None => n.clone(),
				})
				.collect();
			let ty = Type::Tuple(elements.iter().map(|e| one(e).unwrap_or_else(|| e.clone())).collect());
			let own = format!("{{ let ({},) = v; ({},) }}", names.join(", "), owned.join(", "));
			(ty, Some(own))
		}
		ok => match one(ok) {
			Some(ty) => (ty, Some("::std::borrow::ToOwned::to_owned(v)".to_string())),
			None => (ok.clone(), None),
		},
	}
}
