//! React Native's JSI module: C++ over the C ABI that each function of React Native's
//! TypeScript, which [`crate::web::react_native`] writes, forwards to by its C name without
//! the prefix, as `rt.n.<name>`. Each host function converts its arguments from JavaScript's
//! values to the C header's, calls the C function, and converts what it returns, with the
//! checks and errors of the web binding, so the two bindings share one API. What JavaScript
//! implements, a trait, a closure, a waker, a future, or a reader, is a C function of the
//! module whose data holds the JavaScript value, called on the JavaScript thread: from
//! another, it posts there and waits, unless a call into Rust there frees the runtime for
//! this thread meanwhile.
//!
//! The module is `cpp/<prefix>_jsi.cpp`, with [`runtime/rt.jsi.hpp`](../runtime/rt.jsi.hpp)
//! pasted inside its namespace, and needs only `jsi.h`. `cpp/Rust2<Prefix>Module.cpp` is
//! React Native's C++ TurboModule of the codegen spec in `specs/`, whose `install` the
//! binding's `load` calls; the podspec and `android/CMakeLists.txt` build both with the
//! Rust library in `libs/`. A host without React Native installs the module through
//! `rust2_<prefix>::installer`.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write;

use crate::abi::{self, Abi, Ty, pascal};
use crate::ir::{Closure, Family, Function, Int, Type};
use crate::kotlin::strip_refs;
use crate::web::{field_names, lends, method_names, undefinable, variant_fields};

const RUNTIME: &str = include_str!("../runtime/rt.jsi.hpp");

/// The global a host installs the module as, which `load` looks for before React Native's.
pub(crate) fn global(prefix: &str) -> String {
	format!("__rust2_{prefix}")
}

/// The name of React Native's TurboModule that installs the module.
pub(crate) fn module(prefix: &str) -> String {
	format!("Rust2{}", pascal(prefix))
}

/// The module's C++ files, by their names under `cpp/`, serving the targets of `mask`.
pub(crate) fn generate(abi: &Abi<'_>, packages: &str, mask: u64) -> Result<Vec<(String, String)>, String> {
	let mut g = Gen {
		abi,
		mask,
		classes: crate::web::classes(abi),
		protos: Vec::new(),
		defs: BTreeMap::new(),
		order: Vec::new(),
		readers: HashMap::new(),
		writers: HashMap::new(),
		closures: Vec::new(),
		fns: Vec::new(),
		errors: Vec::new(),
	};
	g.items();
	if !g.errors.is_empty() {
		return Err(g.errors.join("\n"));
	}
	let p = &abi.prefix;
	let ns = format!("rust2_{p}");
	let mut out = format!(
		"// Generated by rust2-ffi: the JSI module of the pub API of {packages}, for React Native. Do not edit.\n\n\
		#include \"{p}.h\"\n#include \"{p}_jsi.h\"\n\n"
	);
	for include in [
		"atomic",
		"cmath",
		"condition_variable",
		"cstdint",
		"cstdio",
		"cstdlib",
		"cstring",
		"deque",
		"functional",
		"limits",
		"memory",
		"mutex",
		"optional",
		"string",
		"thread",
		"utility",
		"vector",
	] {
		let _ = writeln!(out, "#include <{include}>");
	}
	out.push_str("#if defined(__ANDROID__)\n#include <android/log.h>\n#endif\n\n");
	let _ = writeln!(out, "namespace {ns} {{\n");
	// The C items the runtime names.
	for t in [
		"buf",
		"u128",
		"duration",
		"ipv4_addr",
		"ipv6_addr",
		"ip_addr",
		"socket_addr_v4",
		"socket_addr_v6",
		"socket_addr",
		"waker",
		"foreign_future",
		"foreign_reader",
	] {
		let _ = writeln!(out, "using c_{t} = ::{p}_{t};");
	}
	let _ = write!(
		out,
		"\ninline void c_buf_free(c_buf b) {{\n\t::{p}_buf_free(b);\n}}\n\ninline c_buf c_buf_copy(c_buf b) {{\n\treturn ::{p}_buf_copy(b);\n}}\n\ninline c_buf c_buf_clone(c_buf b) {{\n\treturn ::{p}_buf_clone(b);\n}}\n\ninline ::std::uint32_t c_target() {{\n\treturn ::{p}_target();\n}}\n\n"
	);
	match abi.api.unsent() {
		true => {
			let _ = write!(
				out,
				"inline constexpr bool c_drains = true;\n\ninline void c_thread_wake(c_waker w) {{\n\t::{p}_thread_wake(w);\n}}\n\ninline void c_thread_drain() {{\n\t::{p}_thread_drain();\n}}\n\n"
			);
		}
		false => out.push_str(
			"inline constexpr bool c_drains = false;\n\ninline void c_thread_wake(c_waker) {}\n\ninline void c_thread_drain() {}\n\n",
		),
	}
	out.push_str(RUNTIME);
	out.push_str("\nnamespace {\n\nnamespace jsi = facebook::jsi;\n\n");
	for proto in &g.protos {
		out.push_str(proto);
		out.push('\n');
	}
	out.push('\n');
	for name in &g.order {
		out.push_str(&g.defs[name]);
	}
	out.push_str("} // namespace\n\n");
	// Installing it.
	let regs: String = (g.fns.iter())
		.map(|(name, argc)| format!("\tfn(\"{name}\", {argc}, &f_{name});\n"))
		.collect();
	let _ = write!(
		out,
		"void install(jsi::Runtime &rt, ::std::function<void(::std::function<void(jsi::Runtime &)>)> post, jsi::Object kit) {{\n\
		\tr::install(rt, ::std::move(post), ::std::move(kit));\n\
		\tjsi::Object n = r::W().kit.getPropertyAsObject(rt, \"natives\");\n\
		\tr::natives(rt, n);\n\
		\tauto fn = [&](const char *name, unsigned argc, jsi::Value (*f)(jsi::Runtime &, const jsi::Value &, const jsi::Value *, ::std::size_t)) {{\n\
		\t\tn.setProperty(rt, name, jsi::Function::createFromHostFunction(rt, jsi::PropNameID::forAscii(rt, name), argc, f));\n\
		\t}};\n\
		\tfn(\"contract\", 0, [](jsi::Runtime &rt, const jsi::Value &, const jsi::Value *, ::std::size_t) -> jsi::Value {{\n\
		\t\treturn jsi::BigInt::fromUint64(rt, ::{p}_contract());\n\
		\t}});\n\
		\tfn(\"target\", 0, [](jsi::Runtime &, const jsi::Value &, const jsi::Value *, ::std::size_t) -> jsi::Value {{\n\
		\t\treturn static_cast<double>(::{p}_target());\n\
		\t}});\n\
		{regs}}}\n\n\
		jsi::Object installer(jsi::Runtime &rt, ::std::function<void(::std::function<void(jsi::Runtime &)>)> post) {{\n\
		\tjsi::Object o(rt);\n\
		\to.setProperty(rt, \"install\", jsi::Function::createFromHostFunction(rt, jsi::PropNameID::forAscii(rt, \"install\"), 1,\n\
		\t\t[post](jsi::Runtime &rt, const jsi::Value &, const jsi::Value *a, ::std::size_t n) -> jsi::Value {{\n\
		\t\t\tinstall(rt, post, r::arg(a, n, 0).getObject(rt));\n\
		\t\t\treturn true;\n\
		\t\t}}));\n\
		\treturn o;\n\
		}}\n\n\
		}} // namespace {ns}\n"
	);
	let header = format!(
		"// Generated by rust2-ffi: the JSI module of the pub API of {packages}, for React Native. Do not edit.\n\n\
		#pragma once\n\n#include <functional>\n\n#include <jsi/jsi.h>\n\n\
		namespace {ns} {{\n\n\
		/// Install the module into `rt` for the binding's `load`, which passes `kit`: `post` runs a\n\
		/// job on the runtime's thread later, as React Native's `CallInvoker` does.\n\
		void install(facebook::jsi::Runtime &rt, ::std::function<void(::std::function<void(facebook::jsi::Runtime &)>)> post, facebook::jsi::Object kit);\n\n\
		/// An object whose `install` installs the module, which a host without React Native sets\n\
		/// as `globalThis.{global}` for the binding's `load` to find.\n\
		facebook::jsi::Object installer(facebook::jsi::Runtime &rt, ::std::function<void(::std::function<void(facebook::jsi::Runtime &)>)> post);\n\n\
		}} // namespace {ns}\n",
		global = global(p)
	);
	let module = module(p);
	let class = format!("{module}Module");
	let spec = format!("{module}Spec");
	// React Native's TurboModule, of the codegen spec `specs/` holds, whose `install(kit)`
	// installs the module into the runtime that calls it, posting through its `CallInvoker`.
	let turbo_h = format!(
		"// Generated by rust2-ffi: React Native's TurboModule installing the JSI module of the pub API of\n// {packages}. Do not edit.\n\n\
		#pragma once\n\n#include <{spec}JSI.h>\n\n#include <memory>\n\n\
		namespace facebook::react {{\n\n\
		/// The module `{module}`, which the binding's `load` installs the JSI module through.\n\
		class {class} : public Native{module}CxxSpec<{class}> {{\n\
		public:\n\
		\texplicit {class}(::std::shared_ptr<CallInvoker> invoker);\n\n\
		\t/// Install the JSI module into `rt`, with the binding's `kit`.\n\
		\tbool install(jsi::Runtime &rt, jsi::Object kit);\n\
		}};\n\n\
		}} // namespace facebook::react\n"
	);
	let turbo_cpp = format!(
		"// Generated by rust2-ffi: React Native's TurboModule installing the JSI module of the pub API of\n// {packages}. Do not edit.\n\n\
		#include \"{class}.h\"\n\n#include \"{p}_jsi.h\"\n\n\
		namespace facebook::react {{\n\n\
		{class}::{class}(::std::shared_ptr<CallInvoker> invoker) : Native{module}CxxSpec(::std::move(invoker)) {{}}\n\n\
		bool {class}::install(jsi::Runtime &rt, jsi::Object kit) {{\n\
		\tauto invoker = jsInvoker_;\n\
		\t{ns}::install(rt, [invoker](::std::function<void(jsi::Runtime &)> job) {{\n\
		\t\tinvoker->invokeAsync([job = ::std::move(job)](jsi::Runtime &rt) {{ job(rt); }});\n\
		\t}}, ::std::move(kit));\n\
		\treturn true;\n\
		}}\n\n\
		}} // namespace facebook::react\n"
	);
	// iOS registers the module as its class loads, which CocoaPods' `-ObjC` keeps; Android's
	// autolinking makes it by `react-native.config.cjs`.
	let on_load = format!(
		"// Generated by rust2-ffi: registers React Native's TurboModule `{module}`. Do not edit.\n\n\
		#import <Foundation/Foundation.h>\n#import <ReactCommon/CxxTurboModuleUtils.h>\n\n#import \"{class}.h\"\n\n\
		@interface {module}OnLoad : NSObject\n@end\n\n\
		@implementation {module}OnLoad\n\n\
		+ (void)load\n{{\n\
		\tfacebook::react::registerCxxModuleToGlobalModuleMap(::std::string(facebook::react::{class}::kModuleName),\n\
		\t\t[](::std::shared_ptr<facebook::react::CallInvoker> invoker) {{\n\
		\t\t\treturn ::std::make_shared<facebook::react::{class}>(::std::move(invoker));\n\
		\t\t}});\n\
		}}\n\n@end\n"
	);
	let spec_ts = format!(
		"// Generated by rust2-ffi: the codegen spec of React Native's TurboModule `{module}`, which installs\n// the JSI module of the pub API of {packages}. Do not edit.\n\n\
		import type {{ TurboModule }} from \"react-native\";\nimport {{ TurboModuleRegistry }} from \"react-native\";\n\n\
		export interface Spec extends TurboModule {{\n\
		\tinstall(kit: Object): boolean;\n\
		}}\n\n\
		export default TurboModuleRegistry.getEnforcing<Spec>(\"{module}\");\n"
	);
	let target = format!("rust2_{p}");
	let cmake = format!(
		"# Generated by rust2-ffi: React Native's TurboModule `{module}`, which the app's autolinking\n\
		# builds into its own library, with the Rust library built for its ABI in libs/android. Do not edit.\n\n\
		cmake_minimum_required(VERSION 3.13)\nproject({target} LANGUAGES CXX)\n\n\
		add_library({target} STATIC ../cpp/{p}_jsi.cpp ../cpp/{class}.cpp)\n\
		set_target_properties({target} PROPERTIES CXX_STANDARD 20 CXX_STANDARD_REQUIRED ON CXX_EXTENSIONS OFF)\n\
		target_include_directories({target} PUBLIC ../cpp ../include)\n\
		target_link_libraries({target} jsi reactnative react_codegen_{spec}\n\
		\t${{CMAKE_CURRENT_SOURCE_DIR}}/../libs/android/${{ANDROID_ABI}}/lib{p}.a log dl m)\n"
	);
	let config = format!(
		"// Generated by rust2-ffi: how React Native's autolinking builds the TurboModule `{module}`. Do\n// not edit.\n\n\
		module.exports = {{\n\
		\tdependency: {{\n\
		\t\tplatforms: {{\n\
		\t\t\tandroid: {{\n\
		\t\t\t\tcxxModuleCMakeListsModuleName: \"{target}\",\n\
		\t\t\t\tcxxModuleCMakeListsPath: \"CMakeLists.txt\",\n\
		\t\t\t\tcxxModuleHeaderName: \"{class}\",\n\
		\t\t\t}},\n\
		\t\t}},\n\
		\t}},\n\
		}};\n"
	);
	let podspec = format!(
		"# Generated by rust2-ffi: React Native's TurboModule `{module}`, with the Rust library built for\n\
		# iOS devices and simulators in libs/ios. Do not edit.\n\n\
		require \"json\"\n\n\
		package = JSON.parse(File.read(File.join(__dir__, \"package.json\")))\n\n\
		Pod::Spec.new do |s|\n\
		\x20 s.name = \"{module}\"\n\
		\x20 s.version = package[\"version\"]\n\
		\x20 s.summary = package[\"description\"]\n\
		\x20 s.homepage = package[\"homepage\"] || \"https://crates.io/crates/#{{package[\"name\"]}}\"\n\
		\x20 s.license = package[\"license\"] || \"UNLICENSED\"\n\
		\x20 s.authors = package[\"author\"] || \"rust2-ffi\"\n\
		\x20 s.platforms = {{ :ios => min_ios_version_supported }}\n\
		\x20 s.source = {{ :git => s.homepage, :tag => s.version.to_s }}\n\
		\x20 s.source_files = \"cpp/*.{{h,cpp}}\", \"ios/*.mm\", \"include/*.h\"\n\
		\x20 s.vendored_frameworks = \"libs/ios/{p}.xcframework\"\n\
		\x20 install_modules_dependencies(s)\n\
		end\n"
	);
	Ok(vec![
		(format!("cpp/{p}_jsi.cpp"), out),
		(format!("cpp/{p}_jsi.h"), header),
		(format!("cpp/{class}.h"), turbo_h),
		(format!("cpp/{class}.cpp"), turbo_cpp),
		(format!("ios/{module}OnLoad.mm"), on_load),
		(format!("specs/Native{module}.ts"), spec_ts),
		("android/CMakeLists.txt".to_string(), cmake),
		("react-native.config.cjs".to_string(), config),
		(format!("{module}.podspec"), podspec),
	])
}

struct Gen<'a> {
	abi: &'a Abi<'a>,
	/// The API's targets the module serves, one bit each.
	mask: u64,
	/// Each exported type's TypeScript name, by its C name.
	classes: HashMap<String, String>,
	/// Each helper's declaration, so any defines in any order.
	protos: Vec<String>,
	/// Each helper's definition, by name, in `order`.
	defs: BTreeMap<String, String>,
	order: Vec<String>,
	readers: HashMap<Type, String>,
	/// Each writer, by its type and whether Rust takes the buffers it writes.
	writers: HashMap<(Type, bool), String>,
	/// Each closure type, whose trampolines are `c<n>`.
	closures: Vec<Type>,
	/// Each host function, by its name, and how many arguments it takes.
	fns: Vec<(String, usize)>,
	errors: Vec<String>,
}

/// Each line of `code` indented one tab more.
fn indent(code: &str) -> String {
	code.lines()
		.map(|l| match l.is_empty() {
			true => String::new(),
			false => format!("\t{l}"),
		})
		.collect::<Vec<_>>()
		.join("\n")
}

/// A C++ string literal of `s`.
fn lit(s: &str) -> String {
	serde_json::Value::from(s).to_string()
}

impl<'a> Gen<'a> {
	fn bare<'n>(&self, c: &'n str) -> &'n str {
		&c[self.abi.prefix.len() + 1..]
	}

	fn class(&self, c: &str) -> String {
		self.classes.get(c).cloned().unwrap_or_else(|| pascal(self.bare(c)))
	}

	fn here(&self, on: crate::ir::On) -> bool {
		on.0 & self.mask != 0
	}

	/// The check that the library's target has an item on `on`, if the module serves a
	/// target that lacks it.
	fn lacks(&self, on: crate::ir::On, what: &str) -> String {
		match on.0 & self.mask == self.mask {
			true => String::new(),
			false => format!("r::lacks(rt, 0x{:x}ull, {});\n", on.0, lit(what)),
		}
	}

	/// The C type of `ty`, declaring `name`.
	fn decl(&self, ty: &Ty, name: &str) -> String {
		crate::c::decl(self.abi, ty, name)
	}

	/// Define the helper `name`, declared by `proto`, as `def`.
	fn define(&mut self, name: &str, proto: String, def: String) {
		self.protos.push(format!("{proto};"));
		self.defs.insert(name.to_string(), def);
		self.order.push(name.to_string());
	}

	/// A helper's name, `base` and a number apart from every other's.
	fn helper_name(&mut self, base: &str) -> String {
		let mut name = base.to_string();
		for k in 2.. {
			if !self.defs.contains_key(&name) {
				break;
			}
			name = format!("{base}_{k}");
		}
		self.defs.insert(name.clone(), String::new());
		name
	}

	// Values from C.

	/// The JavaScript value of `e`, a C value of `ty`: Rust's to free where `own`, else lent.
	fn lift(&mut self, ty: &Type, e: &str, own: bool) -> String {
		let abi = self.abi;
		let o = if own { "true" } else { "false" };
		match ty {
			Type::Unit => "jsi::Value::undefined()".to_string(),
			Type::Bool => format!("jsi::Value(static_cast<bool>({e}))"),
			Type::Int(Int::U64) | Type::NonZero(Int::U64) | Type::Int(Int::Usize) | Type::NonZero(Int::Usize) => {
				format!("r::of_u64(rt, static_cast<::std::uint64_t>({e}))")
			}
			Type::Int(Int::I64) | Type::NonZero(Int::I64) | Type::Int(Int::Isize) | Type::NonZero(Int::Isize) => {
				format!("r::of_i64(rt, static_cast<::std::int64_t>({e}))")
			}
			Type::Int(_) | Type::NonZero(_) | Type::Char => format!("jsi::Value(static_cast<double>({e}))"),
			Type::F32 => format!("r::of_f32(rt, {e})"),
			Type::F64 => format!("r::of_f64(rt, {e})"),
			Type::U128 => format!("r::of_u128(rt, {e})"),
			Type::Str | Type::String => format!("r::str(rt, {e}, {o})"),
			Type::Slice | Type::Vec | Type::Bytes => format!("r::u8s(rt, {e}, {o})"),
			Type::Path | Type::PathBuf => format!("r::of_path(rt, {e}, {o})"),
			Type::Duration => format!("r::of_duration(rt, {e})"),
			Type::Array(n) => format!("r::u8s(rt, c_buf{{({e}).items, {n}, nullptr}}, false)"),
			Type::SocketAddr(Family::Any) => format!("r::of_socket(rt, {e})"),
			Type::SocketAddr(Family::V4) => format!("r::of_socket_v4(rt, {e})"),
			Type::SocketAddr(Family::V6) => format!("r::of_socket_v6(rt, {e})"),
			Type::IpAddr(Family::Any) => format!("r::of_ip(rt, {e})"),
			Type::IpAddr(Family::V4) => format!("r::of_ipv4(rt, {e})"),
			Type::IpAddr(Family::V6) => format!("r::of_ipv6(rt, {e})"),
			Type::Waker => format!("r::of_waker(rt, {e})"),
			Type::Object(i) => {
				let kind = self.kind(*i);
				format!("r::made(rt, {e}, {kind}, {o})")
			}
			Type::Option(inner) if matches!(inner.base(), Type::Object(_)) => {
				let some = self.lift(inner.base(), e, own);
				format!("(({e}) == nullptr ? jsi::Value::undefined() : {some})")
			}
			Type::Option(inner) if Abi::is_buf(inner) || matches!(inner.base(), Type::List(..)) => {
				let some = self.lift(inner.base(), e, own);
				format!("(({e}).ptr == nullptr ? jsi::Value::undefined() : {some})")
			}
			Type::Box(inner) | Type::Ref(_, inner) => self.lift(inner, e, own),
			Type::Enum(i) if abi.api.enums[*i].plain() => {
				let lift = self.enum_lift(*i);
				format!("{lift}(rt, {e})")
			}
			Type::Record(_)
			| Type::Enum(_)
			| Type::Option(_)
			| Type::List(..)
			| Type::Tuple(_)
			| Type::Range(_)
			| Type::Bound(_)
			| Type::Bounds(_) => {
				let r = self.reader(ty);
				format!("{r}(rt, {e}, {o})")
			}
			other => unreachable!("{other:?} is never lifted"),
		}
	}

	/// [`Self::lift`] of a value a reader reads, owned as its `o` says.
	fn lift_o(&mut self, ty: &Type, e: &str) -> String {
		let owned = self.lift(ty, e, true);
		let lent = self.lift(ty, e, false);
		match owned == lent {
			true => owned,
			false => format!("(o ? {owned} : {lent})"),
		}
	}

	/// The value of type `ty` a call returned as `e`: bytes as an `rt.Bytes`, which may lend
	/// Rust's buffer.
	fn returned(&mut self, ty: &Type, e: &str) -> String {
		match ty {
			ty if lends(ty) => format!("r::returned(rt, {e})"),
			Type::Option(inner) if lends(inner) => {
				format!("(({e}).ptr == nullptr ? jsi::Value::undefined() : r::returned(rt, {e}))")
			}
			_ => self.lift(ty, e, true),
		}
	}

	/// The value Rust passes a call into JavaScript as `e`: bytes and text lent, which it
	/// copies, any other value given, and an object it lends closed after the call.
	fn incoming(&mut self, ty: &Type, e: &str) -> String {
		match ty {
			Type::Ref(_, inner) if let Type::Object(i) = **inner => {
				let kind = self.kind(i);
				format!("f.lend(const_cast<void *>(static_cast<const void *>({e})), {kind})")
			}
			Type::Ref(_, inner) => self.incoming(inner, e),
			ty if Abi::is_buf(ty) => self.lift(ty, e, false),
			Type::Option(inner) if Abi::is_buf(inner) => self.lift(ty, e, false),
			ty => self.lift(ty, e, true),
		}
	}

	/// The handles of object `i`: its kind, defined once.
	fn kind(&mut self, i: usize) -> String {
		let abi = self.abi;
		let c = abi.object(i);
		let c_ = crate::abi::stem(&c);
		let name = format!("k_{}", self.bare(&c));
		if !self.defs.contains_key(&name) {
			let class = self.class(&c);
			let drop = match abi.checked[i] {
				true => format!("[](void *p, ::std::int32_t *s) {{ ::{c_}_drop(static_cast<{c} *>(p), s); }}"),
				false => "nullptr".to_string(),
			};
			self.define(
				&name,
				format!("extern const r::kind {name}"),
				format!(
					"const r::kind {name}{{{}, [](void *p) {{ ::{c_}_free(static_cast<{c} *>(p)); }}, {drop}, {}}};\n\n",
					lit(&class),
					lit(&format!("{c_}_drop")),
				),
			);
		}
		name
	}

	/// The helper making a plain enum `i`'s variant name of its C value.
	fn enum_lift(&mut self, i: usize) -> String {
		let abi = self.abi;
		let c = abi.enumeration(i);
		let name = format!("e_{}", self.bare(&c));
		if !self.defs.contains_key(&name) {
			let e = &abi.api.enums[i];
			let cases: Vec<String> = (e.variants.iter())
				.filter(|v| self.here(v.on))
				.map(|v| format!("\tcase {}:\n\t\treturn r::ascii(rt, {});", v.discriminant, lit(&v.name)))
				.collect();
			let proto = format!("jsi::Value {name}(jsi::Runtime &rt, {c} v)");
			self.define(
				&name,
				proto.clone(),
				format!(
					"{proto} {{\n\tswitch (static_cast<::std::int64_t>(v)) {{\n{}\n\tdefault:\n\t\tr::range(rt, \"{c}: an invalid value \" + ::std::to_string(static_cast<::std::int64_t>(v)));\n\t}}\n}}\n\n",
					cases.join("\n")
				),
			);
		}
		name
	}

	/// The helper making a plain enum `i`'s C value of its variant name.
	fn enum_lower(&mut self, i: usize) -> String {
		let abi = self.abi;
		let c = abi.enumeration(i);
		let name = format!("l_{}", self.bare(&c));
		if !self.defs.contains_key(&name) {
			let e = &abi.api.enums[i];
			let t = self.class(&c);
			let cases: Vec<String> = (e.variants.iter())
				.filter(|v| self.here(v.on))
				.map(|v| {
					format!(
						"\tif (s == {}) {{\n\t\treturn static_cast<{c}>({});\n\t}}",
						lit(&v.name),
						v.discriminant
					)
				})
				.collect();
			let proto = format!("{c} {name}(jsi::Runtime &rt, const jsi::Value &v)");
			self.define(
				&name,
				proto.clone(),
				format!(
					"{proto} {{\n\t::std::string s = r::text(rt, v);\n{}\n\tr::range(rt, r::shown(rt, v) + \" is no {t}\");\n}}\n\n",
					cases.join("\n")
				),
			);
		}
		name
	}

	/// The C struct of `ty`.
	fn struct_of(&self, ty: &Type) -> String {
		match self.abi.ty(ty) {
			Ty::Struct(c) => c,
			other => unreachable!("{other:?} is no struct"),
		}
	}

	/// The helper reading a value of type `ty`, a struct's.
	fn reader(&mut self, ty: &Type) -> String {
		if let Some(name) = self.readers.get(ty) {
			return name.clone();
		}
		let abi = self.abi;
		let c = self.struct_of(ty);
		let name = self.helper_name(&format!("r_{}", self.bare(&c)));
		self.readers.insert(ty.clone(), name.clone());
		let body = self.read_body(ty, &c);
		let proto = format!("jsi::Value {name}(jsi::Runtime &rt, const {c} &v, bool o)");
		self.define(
			&name,
			proto.clone(),
			format!(
				"// A `{}`.\n{proto} {{\n\t(void)rt;\n\t(void)o;\n{}\n}}\n\n",
				abi.spell(ty),
				indent(&body)
			),
		);
		name
	}

	fn read_body(&mut self, ty: &Type, c: &str) -> String {
		let abi = self.abi;
		let c_ = crate::abi::stem(c);
		match ty {
			Type::Record(i) if abi.api.records[*i].opaque.is_some() => {
				"return r::opaque(rt, &v, sizeof v);".to_string()
			}
			Type::Record(i) => {
				let record = &abi.api.records[*i];
				let mut lines = vec!["jsi::Object out(rt);".to_string()];
				for (f, name) in record.fields.iter().zip(field_names(&record.fields)) {
					let value = self.lift_o(&f.ty, &format!("v.{}", abi::escape(&f.name)));
					lines.push(format!("out.setProperty(rt, {}, {value});", lit(&name)));
				}
				lines.push("return out;".to_string());
				lines.join("\n")
			}
			Type::Enum(i) => {
				let e = &abi.api.enums[*i];
				let mut cases = Vec::new();
				for (n, variant) in e.variants.iter().enumerate() {
					if !self.here(variant.on) {
						continue;
					}
					let mut lines = vec![
						"jsi::Object out(rt);".to_string(),
						format!("out.setProperty(rt, \"tag\", r::ascii(rt, {}));", lit(&variant.name)),
					];
					let member = abi::variant_member(&variant.name);
					for (f, name) in variant.fields.iter().zip(variant_fields(&variant.fields)) {
						let value = self.lift_o(&f.ty, &format!("v.{member}.{}", abi::escape(&f.name)));
						lines.push(format!("out.setProperty(rt, {}, {value});", lit(&name)));
					}
					lines.push("return out;".to_string());
					cases.push(format!("case {n}: {{\n{}\n}}", indent(&lines.join("\n"))));
				}
				format!(
					"switch (static_cast<int>(v.tag)) {{\n{}\ndefault:\n\tr::range(rt, \"{c}: an invalid tag\");\n}}",
					cases.join("\n")
				)
			}
			Type::Option(inner) => {
				let value = self.lift_o(inner, "v.value");
				let none = match undefinable(inner) {
					true => "jsi::Value(rt, r::W().none)",
					false => "jsi::Value::undefined()",
				};
				format!("return v.some ? {value} : {none};")
			}
			Type::List(..) if let Some(block) = ty.block() => {
				let array = crate::web::typed_array(block);
				format!(
					"jsi::Value out = r::typed(rt, \"{array}\", v.ptr, v.len, sizeof *v.ptr);\nif (o) {{\n\t::{c_}_free(v);\n}}\nreturn out;"
				)
			}
			Type::List(_, elem) => {
				let item = self.lift_o(elem, "v.ptr[i]");
				format!(
					"jsi::Array out(rt, v.len);\nfor (::std::size_t i = 0; i < v.len; i++) {{\n\tout.setValueAtIndex(rt, i, {item});\n}}\nif (o) {{\n\t{c} rest = v;\n\trest.len = 0;\n\t::{c_}_free(rest);\n}}\nreturn out;"
				)
			}
			Type::Tuple(elements) => {
				let mut lines = vec![format!("jsi::Array out(rt, {});", elements.len())];
				for (n, e) in elements.iter().enumerate() {
					let value = self.lift_o(e, &format!("v._{n}"));
					lines.push(format!("out.setValueAtIndex(rt, {n}, {value});"));
				}
				lines.push("return out;".to_string());
				lines.join("\n")
			}
			Type::Range(int) => {
				let int = Type::Int(*int);
				let start = self.lift(&int, "v.start", true);
				let end = self.lift(&int, "v.end", true);
				format!(
					"jsi::Object out(rt);\nout.setProperty(rt, \"start\", {start});\nout.setProperty(rt, \"end\", {end});\nreturn out;"
				)
			}
			Type::Bound(int) => {
				let value = self.lift(&Type::Int(*int), "v.value", true);
				format!(
					"jsi::Object out(rt);\nswitch (static_cast<int>(v.kind)) {{\ncase 0:\n\tout.setProperty(rt, \"tag\", r::ascii(rt, \"Unbounded\"));\n\treturn out;\ncase 1:\n\tout.setProperty(rt, \"tag\", r::ascii(rt, \"Included\"));\n\tbreak;\ncase 2:\n\tout.setProperty(rt, \"tag\", r::ascii(rt, \"Excluded\"));\n\tbreak;\ndefault:\n\tr::range(rt, \"{c}: an invalid kind\");\n}}\nout.setProperty(rt, \"_0\", {value});\nreturn out;"
				)
			}
			Type::Bounds(int) => {
				let bound = Type::Bound(*int);
				let start = self.lift_o(&bound, "v.start");
				let end = self.lift_o(&bound, "v.end");
				format!(
					"jsi::Object out(rt);\nout.setProperty(rt, \"start\", {start});\nout.setProperty(rt, \"end\", {end});\nreturn out;"
				)
			}
			other => unreachable!("{other:?} has no reader"),
		}
	}

	// Values into C.

	/// The checked integer `ty` of the JavaScript value `v`.
	fn int(&self, ty: &Type, v: &str) -> String {
		match ty {
			Type::NonZero(int) => format!("r::nonzero(rt, {})", self.int(&Type::Int(*int), v)),
			Type::Int(int) => {
				let (min, max, c): (i64, i64, &str) = match int {
					Int::U8 => (0, 0xff, "::std::uint8_t"),
					Int::U16 => (0, 0xffff, "::std::uint16_t"),
					Int::U32 => (0, 0xffff_ffff, "::std::uint32_t"),
					Int::I8 => (-0x80, 0x7f, "::std::int8_t"),
					Int::I16 => (-0x8000, 0x7fff, "::std::int16_t"),
					Int::I32 => (-0x8000_0000, 0x7fff_ffff, "::std::int32_t"),
					Int::U64 => return format!("r::u64(rt, {v})"),
					Int::I64 => return format!("r::i64(rt, {v})"),
					Int::Usize => return format!("r::usize(rt, {v})"),
					Int::Isize => return format!("r::isize(rt, {v})"),
				};
				format!("r::int_<{c}>(rt, {v}, {min}, {max}, \"{}\")", int.rust())
			}
			Type::Char => format!("r::char_(rt, {v})"),
			other => unreachable!("{other:?} is no integer"),
		}
	}

	/// Statements writing the C value of the JavaScript value `v` of type `ty` to `out`:
	/// bytes and text as views held until the call returns, unless `take`, where Rust takes
	/// a buffer of its own.
	fn lower(&mut self, ty: &Type, v: &str, out: &str, take: bool) -> String {
		let abi = self.abi;
		match ty {
			Type::Unit => String::new(),
			Type::Bool => format!("{out} = r::bool_(rt, {v});"),
			Type::Int(_) | Type::NonZero(_) | Type::Char => format!("{out} = {};", self.int(ty, v)),
			Type::F32 => format!("{out} = r::f32(rt, {v});"),
			Type::F64 => format!("{out} = r::f64(rt, {v});"),
			Type::U128 => format!("{out} = r::u128(rt, {v});"),
			Type::Str | Type::String => match take {
				true => format!("{out} = c_buf_copy(f.utf8({v}));"),
				false => format!("{out} = f.utf8({v});"),
			},
			Type::Slice | Type::Vec | Type::Bytes => match take {
				true => format!("{out} = c_buf_copy(f.view({v}));"),
				false => format!("{out} = f.view({v});"),
			},
			Type::Path | Type::PathBuf => match take {
				true => format!("{out} = c_buf_copy(r::path(f, {v}));"),
				false => format!("{out} = r::path(f, {v});"),
			},
			Type::Duration => format!("r::duration(f, {v}, {out});"),
			Type::Array(n) => format!("f.fixed({v}, {out}.items, {n});"),
			Type::SocketAddr(Family::Any) => format!("r::socket(f, {v}, {out});"),
			Type::SocketAddr(Family::V4) => format!("r::socket_v4(f, {v}, {out});"),
			Type::SocketAddr(Family::V6) => format!("r::socket_v6(f, {v}, {out});"),
			Type::IpAddr(Family::Any) => format!("r::ip(f, {v}, {out});"),
			Type::IpAddr(Family::V4) => format!("r::ipv4(f, {v}, {out});"),
			Type::IpAddr(Family::V6) => format!("r::ipv6(f, {v}, {out});"),
			Type::Object(i) => {
				let kind = self.kind(*i);
				let c = abi.object(*i);
				format!("{out} = static_cast<{c} *>(f.hold({v}, {kind}));")
			}
			Type::Option(inner) if let Type::Object(i) = inner.base() => {
				let kind = self.kind(*i);
				let c = abi.object(*i);
				format!("{out} = static_cast<{c} *>(f.hold_or({v}, {kind}));")
			}
			Type::Option(inner) if Abi::is_buf(inner) => {
				let some = self.lower(inner.base(), v, out, take);
				format!(
					"if (({v}).isUndefined()) {{\n\t{out} = c_buf{{}};\n}} else {{\n{}\n}}",
					indent(&some)
				)
			}
			Type::Option(inner) if matches!(inner.base(), Type::List(..)) => {
				let some = self.lower(inner.base(), v, out, take);
				format!(
					"if (({v}).isUndefined()) {{\n\t{out} = {{}};\n}} else {{\n{}\n}}",
					indent(&some)
				)
			}
			Type::Box(inner) | Type::Ref(_, inner) => self.lower(inner, v, out, take),
			Type::Enum(i) if abi.api.enums[*i].plain() => {
				let lower = self.enum_lower(*i);
				format!("{out} = {lower}(rt, {v});")
			}
			Type::Callback(i, _) => {
				let vtable = self.vtable(*i);
				let name = self.class(&abi.callback(*i));
				format!(
					"{out} = {{&{vtable}, new r::remote(rt, r::obj(rt, {v}, {}))}};",
					lit(&name)
				)
			}
			Type::Waker => format!("{out} = r::waker_of(rt, {v});"),
			Type::Future => format!("{out} = r::future_of(rt, {v});"),
			Type::Reader => format!("{out} = r::reader_of(f, {v});"),
			Type::Record(_)
			| Type::Enum(_)
			| Type::Option(_)
			| Type::List(..)
			| Type::Tuple(_)
			| Type::Range(_)
			| Type::Bound(_)
			| Type::Bounds(_) => {
				let w = self.writer(ty, take);
				format!("{w}(rt, f, {v}, {out});")
			}
			other => unreachable!("{other:?} is never lowered"),
		}
	}

	/// The helper writing a value of type `ty`, a struct's: buffers Rust takes where `take`.
	fn writer(&mut self, ty: &Type, take: bool) -> String {
		if let Some(name) = self.writers.get(&(ty.clone(), take)) {
			return name.clone();
		}
		let abi = self.abi;
		let c = self.struct_of(ty);
		let base = match take {
			true => format!("t_{}", self.bare(&c)),
			false => format!("w_{}", self.bare(&c)),
		};
		let name = self.helper_name(&base);
		self.writers.insert((ty.clone(), take), name.clone());
		let body = self.write_body(ty, &c, take);
		let proto = format!("void {name}(jsi::Runtime &rt, r::frame &f, const jsi::Value &v, {c} &out)");
		self.define(
			&name,
			proto.clone(),
			format!(
				"// Write the `{}` `v`.\n{proto} {{\n\t(void)rt;\n\t(void)f;\n{}\n}}\n\n",
				abi.spell(ty),
				indent(&body)
			),
		);
		name
	}

	fn write_body(&mut self, ty: &Type, c: &str, take: bool) -> String {
		let abi = self.abi;
		let class = |c: &str| self.class(c);
		match ty {
			Type::Record(i) if abi.api.records[*i].opaque.is_some() => {
				"r::opaque_put(f, v, &out, sizeof out);".to_string()
			}
			Type::Record(i) => {
				let record = &abi.api.records[*i];
				let mut lines = vec![format!("jsi::Object o = r::obj(rt, v, {});", lit(&class(c)))];
				for (f, name) in record.fields.iter().zip(field_names(&record.fields)) {
					let field = format!("out.{}", abi::escape(&f.name));
					lines.push(self.lower(&f.ty, &format!("o.getProperty(rt, {})", lit(&name)), &field, take));
				}
				lines.join("\n")
			}
			Type::Enum(i) => {
				let e = &abi.api.enums[*i];
				let mut lines = vec![
					format!("::std::string tag = r::tag_of(rt, v, {});", lit(&class(c))),
					"jsi::Object o = v.getObject(rt);".to_string(),
					"(void)o;".to_string(),
				];
				for (n, variant) in e.variants.iter().enumerate() {
					if !self.here(variant.on) {
						continue;
					}
					let member = abi::variant_member(&variant.name);
					let mut body = vec![format!("out.tag = static_cast<decltype(out.tag)>({n});")];
					for (f, name) in variant.fields.iter().zip(variant_fields(&variant.fields)) {
						let field = format!("out.{member}.{}", abi::escape(&f.name));
						body.push(self.lower(&f.ty, &format!("o.getProperty(rt, {})", lit(&name)), &field, take));
					}
					body.push("return;".to_string());
					lines.push(format!(
						"if (tag == {}) {{\n{}\n}}",
						lit(&variant.name),
						indent(&body.join("\n"))
					));
				}
				lines.push(format!(
					"r::range(rt, r::shown(rt, o.getProperty(rt, \"tag\")) + \" is no variant of {c}\");"
				));
				lines.join("\n")
			}
			Type::Option(inner) => {
				let some = self.lower(inner, "v", "out.value", take);
				let none = match undefinable(inner) {
					true => "r::none(rt, v)",
					false => "v.isUndefined()",
				};
				format!("if ({none}) {{\n\tout.some = false;\n\treturn;\n}}\nout.some = true;\n{some}")
			}
			Type::List(..) if take => {
				self.errors.push(format!(
					"`{}` returned from JavaScript to Rust has no React Native form yet, which rust2-ffi should give it",
					abi.spell(ty)
				));
				String::new()
			}
			Type::List(..) if let Some(block) = ty.block() => {
				let array = crate::web::typed_array(block);
				format!(
					"if (v.isUndefined()) {{\n\tout = {{}};\n\treturn;\n}}\nc_buf b = f.array(v, \"{array}\");\nout.ptr = reinterpret_cast<decltype(out.ptr)>(b.ptr);\nout.len = b.len / sizeof *out.ptr;\nout.owner = nullptr;"
				)
			}
			Type::List(_, elem) => {
				let elem_c = self.decl(&abi.ty(elem), "");
				let item = self.lower(elem, "x", "p[i]", false);
				format!(
					"if (v.isUndefined()) {{\n\tout = {{}};\n\treturn;\n}}\njsi::Array a = r::arr(rt, v);\n::std::size_t len = a.size(rt);\nauto *p = f.alloc<{elem_c}>(len);\nfor (::std::size_t i = 0; i < len; i++) {{\n\tjsi::Value x = a.getValueAtIndex(rt, i);\n{}\n}}\nout.ptr = p;\nout.len = len;\nout.owner = nullptr;",
					indent(&item)
				)
			}
			Type::Tuple(elements) => {
				let mut lines = vec!["jsi::Array a = r::arr(rt, v);".to_string()];
				for (n, e) in elements.iter().enumerate() {
					lines.push(self.lower(e, &format!("a.getValueAtIndex(rt, {n})"), &format!("out._{n}"), take));
				}
				lines.join("\n")
			}
			Type::Range(int) => {
				let int = Type::Int(*int);
				let start = self.lower(&int, "o.getProperty(rt, \"start\")", "out.start", take);
				let end = self.lower(&int, "o.getProperty(rt, \"end\")", "out.end", take);
				format!("jsi::Object o = r::obj(rt, v, \"Range\");\n{start}\n{end}")
			}
			Type::Bound(int) => {
				let value = self.lower(&Type::Int(*int), "o.getProperty(rt, \"_0\")", "out.value", take);
				format!(
					"::std::string tag = r::tag_of(rt, v, \"Bound\");\njsi::Object o = v.getObject(rt);\nout.value = {{}};\nif (tag == \"Unbounded\") {{\n\tout.kind = static_cast<decltype(out.kind)>(0);\n}} else if (tag == \"Included\") {{\n\tout.kind = static_cast<decltype(out.kind)>(1);\n\t{value}\n}} else if (tag == \"Excluded\") {{\n\tout.kind = static_cast<decltype(out.kind)>(2);\n\t{value}\n}} else {{\n\tr::range(rt, \"a Bound is Included, Excluded, or Unbounded\");\n}}"
				)
			}
			Type::Bounds(int) => {
				let bound = Type::Bound(*int);
				let start = self.lower(&bound, "o.getProperty(rt, \"start\")", "out.start", take);
				let end = self.lower(&bound, "o.getProperty(rt, \"end\")", "out.end", take);
				format!("jsi::Object o = r::obj(rt, v, \"Bounds\");\n{start}\n{end}")
			}
			other => unreachable!("{other:?} has no writer"),
		}
	}
}

/// How a host function's arguments are lowered: statements before the call, and what
/// Rust takes once nothing left to lower can throw, so none is given in vain.
#[derive(Default)]
struct Call {
	lines: Vec<String>,
	gives: Vec<String>,
	args: Vec<String>,
	writes: Vec<String>,
	/// The outs written back to a `&mut` parameter's place.
	written: Vec<String>,
}

impl Gen<'_> {
	fn items(&mut self) {
		let abi = self.abi;
		let api = abi.api;
		for (i, record) in api.records.iter().enumerate() {
			if !self.here(record.on) {
				continue;
			}
			let c = abi.record(i);
			let ty = Type::Record(i);
			self.traits(&ty, &c, record.traits, record.on);
			for method in &record.methods {
				self.function(method, Some((&Ty::Struct(c.clone()), &ty)));
			}
		}
		for (i, e) in api.enums.iter().enumerate() {
			if !self.here(e.on) {
				continue;
			}
			let c = abi.enumeration(i);
			let ty = Type::Enum(i);
			self.traits(&ty, &c, e.traits, e.on);
			let owner = abi.ty(&ty);
			for method in &e.methods {
				self.function(method, Some((&owner, &ty)));
			}
		}
		for (i, object) in api.objects.iter().enumerate() {
			if !self.here(object.on) {
				continue;
			}
			let c = abi.object(i);
			let ty = Type::Object(i);
			self.traits(&ty, &c, object.traits, object.on);
			let owner = Ty::Handle {
				name: c.clone(),
				constant: false,
			};
			for method in &object.methods {
				self.function(method, Some((&owner, &ty)));
			}
		}
		for function in &api.functions {
			self.function(function, None);
		}
	}

	/// Define the host function `name`, taking `argc` arguments, of `body`.
	fn host(&mut self, name: &str, argc: usize, body: &str) {
		let f = format!("f_{name}");
		let proto =
			format!("jsi::Value {f}(jsi::Runtime &rt, const jsi::Value &, const jsi::Value *a, ::std::size_t n)");
		self.define(
			&f,
			proto.clone(),
			format!("{proto} {{\n\t(void)a;\n\t(void)n;\n{}\n}}\n\n", indent(body)),
		);
		self.fns.push((name.to_string(), argc));
	}

	/// The statements lowering the receiver `v` of C type `c`, of type `ty`, as `self_`,
	/// into `call`.
	fn receiver(&mut self, ty: &Type, c: &Ty, v: &str, call: &mut Call) {
		match c {
			Ty::Handle { name, constant } => {
				let Type::Object(i) = ty else {
					unreachable!("a handle's type is an object")
				};
				let kind = self.kind(*i);
				let q = if *constant { "const " } else { "" };
				call.lines
					.push(format!("auto *self_ = static_cast<{q}{name} *>(f.hold({v}, {kind}));"));
				call.args.push("self_".to_string());
			}
			Ty::In(inner) | Ty::InOut(inner) => {
				call.lines.push(format!("{}{{}};", self.decl(inner, "self_")));
				call.lines.push(self.lower(ty, v, "self_", false));
				call.args.push("&self_".to_string());
			}
			other => unreachable!("a receiver is {other:?}"),
		}
	}

	/// `function`'s host function, a method of `owner` if it has one.
	fn function(&mut self, function: &Function, owner: Option<(&Ty, &Type)>) {
		let abi = self.abi;
		if !self.here(function.on) {
			return;
		}
		let export = abi.export(function, owner.map(|(o, _)| o));
		let handed = owner.and_then(|(o, t)| abi.handed_back(function, o, t)).is_some();
		let c_name = export.call.name.clone();
		let name = self.bare(&c_name).to_string();
		let mut call = Call::default();
		call.lines.push(self.lacks(function.on, &function.path.join("::")));
		call.lines.push("r::frame f(rt);".to_string());
		let receiver = function.receiver.filter(|_| owner.is_some());
		let mut c_params = export.call.params.iter();
		let mut k = 0;
		if receiver.is_some() {
			let (_, c) = c_params.next().expect("a method has its receiver");
			let (_, ty) = owner.expect("a method has its type");
			self.receiver(ty, c, "r::arg(a, n, 0)", &mut call);
			k = 1;
		}
		for (j, param) in function.params.iter().enumerate() {
			let (_, c) = c_params.next().expect("each parameter has its C one");
			let v = format!("r::arg(a, n, {k})");
			k += 1;
			let a = format!("a{j}");
			if param.ty.written() {
				let inner = param.ty.base();
				call.lines
					.push(format!("jsi::Object place{j} = r::obj(rt, {v}, \"Place\");"));
				call.lines.push(format!("{}{{}};", self.decl(c, &a)));
				call.lines
					.push(self.lower(inner, &format!("place{j}.getProperty(rt, \"v\")"), &a, false));
				call.args.push(a);
				let out = Abi::written(function, &abi::escape(&param.name));
				let read = self.lift(inner, &format!("o_{out}"), true);
				call.writes.push(format!("place{j}.setProperty(rt, \"v\", {read});"));
				call.written.push(out);
				continue;
			}
			match (&param.ty, c) {
				(Type::Closure(closure), Ty::Fn(..)) => {
					c_params.next().expect("a closure has its data");
					let t = self.closure(&param.ty, closure);
					let check = format!("r::obj(rt, {v}, \"function\")");
					call.args.push(t);
					if closure.kept {
						c_params.next().expect("a kept closure has its free");
						call.gives.push(format!("void *{a} = new r::remote(rt, {check});"));
						call.args.push(a);
						call.args.push("&r::closure_free".to_string());
					} else {
						call.lines.push(format!(
							"auto {a}r = ::std::make_shared<r::remote>(rt, {check});\nf.mem.push_back({a}r);\nvoid *{a} = {a}r.get();"
						));
						call.args.push(a);
					}
				}
				(Type::Callback(..), c) | (Type::Box(_), c @ Ty::Struct(_))
					if matches!(param.ty.base(), Type::Callback(..)) =>
				{
					call.gives.push(format!("{}{{}};", self.decl(c, &a)));
					call.gives.push(self.lower(param.ty.base(), &v, &a, false));
					call.args.push(a);
				}
				(Type::Waker | Type::Future, c) => {
					call.gives.push(format!("{}{{}};", self.decl(c, &a)));
					call.gives.push(self.lower(&param.ty, &v, &a, false));
					call.args.push(a);
				}
				(ty, c) => {
					call.lines.push(format!("{}{{}};", self.decl(c, &a)));
					// Rust takes `Bytes` by value: an `rt.Bytes` passes a second owner of its
					// buffer, once nothing left to lower can throw.
					let owned =
						matches!(ty, Type::Bytes) || matches!(ty, Type::Option(inner) if **inner == Type::Bytes);
					match owned {
						true => {
							call.lines.push(self.lower(ty, &v, &a, false));
							call.gives.push(format!("{a} = f.give({a});"));
						}
						false => call.lines.push(self.lower(ty, &v, &a, false)),
					}
					call.args.push(a);
				}
			}
		}
		let argc = k;
		let rest: Vec<(String, Ty)> = c_params.cloned().collect();
		let ok = strip_refs(&function.ok);
		let err = function.err.as_ref().map(strip_refs);
		let mut lines = std::mem::take(&mut call.lines);
		lines.extend(std::mem::take(&mut call.gives));
		let status = export.call.status().is_some();
		if let Some(abi::Future {
			handle,
			start,
			poll,
			free,
		}) = &export.future
		{
			let poll_outs: Vec<(String, Ty)> = (poll.params[2..].iter())
				.filter(|(_, ty)| !abi::is_status(ty))
				.cloned()
				.collect();
			let outs_decl: Vec<String> = poll_outs.iter().map(|(n, ty)| self.out_decl(n, ty)).collect();
			let ready = match &ok {
				Type::Unit => "jsi::Value::undefined()".to_string(),
				_ => self.lift_outs(&function.ok, &ok),
			};
			let ready = match &err {
				Some(_) => format!("r::ok(rt, {ready})"),
				None => ready,
			};
			let failed = err
				.as_ref()
				.map(|err| format!("r::err(rt, {})", self.lift(err, "o_err", true)));
			// The poll, which completes the future.
			let mut p = vec!["r::frame f(rt);".to_string()];
			p.extend(outs_decl.iter().cloned());
			let mut pargs = vec![format!("static_cast<{handle} *>(p)"), "w".to_string()];
			pargs.extend(poll_outs.iter().map(|(n, _)| format!("&o_{n}")));
			let poll_status = poll.status().is_some();
			if poll_status {
				p.push("::std::int32_t s_ = 0;".to_string());
				pargs.push("&s_".to_string());
			}
			p.push(format!(
				"auto st_ = r::unlocked([&] {{ return ::{}({}); }});",
				poll.name,
				pargs.join(", ")
			));
			if poll_status {
				p.push(format!("r::status(rt, s_, {});", lit(&poll.name)));
			}
			let mut cases = vec![format!("case 1:\n\tresolve.call(rt, {ready});\n\treturn true;")];
			if let Some(failed) = &failed {
				cases.push(format!("case 2:\n\tresolve.call(rt, {failed});\n\treturn true;"));
			}
			cases.push("default:\n\treturn false;".to_string());
			p.push(format!("switch (static_cast<int>(st_)) {{\n{}\n}}", cases.join("\n")));
			let poll_fn = format!(
				"[](jsi::Runtime &rt, void *p, c_waker w, jsi::Function &resolve, jsi::Function &) -> bool {{\n{}\n}}",
				indent(&p.join("\n"))
			);
			// The call and its first poll in one.
			lines.extend(outs_decl);
			call.args.extend(poll_outs.iter().map(|(n, _)| format!("&o_{n}")));
			lines.push(format!("{handle} *fut_ = nullptr;"));
			call.args.push("&fut_".to_string());
			if start.status().is_some() {
				lines.push("::std::int32_t s_ = 0;".to_string());
				call.args.push("&s_".to_string());
			}
			lines.push(format!(
				"auto st_ = r::unlocked([&] {{ return ::{}({}); }});",
				start.name,
				call.args.join(", ")
			));
			if start.status().is_some() {
				lines.push(format!("r::status(rt, s_, {});", lit(&start.name)));
			}
			let mut cases = vec![format!("case 1:\n\treturn r::ready(rt, {ready});")];
			if let Some(failed) = &failed {
				cases.push(format!("case 2:\n\treturn r::ready(rt, {failed});"));
			}
			cases.push(format!(
				"default:\n\treturn r::pend(rt, fut_, [](void *p) {{ ::{}(static_cast<{handle} *>(p)); }},\n{});",
				free.name,
				indent(&indent(&poll_fn))
			));
			lines.push(format!("switch (static_cast<int>(st_)) {{\n{}\n}}", cases.join("\n")));
		} else {
			let outs: Vec<(String, Ty)> = rest.iter().filter(|(_, ty)| !abi::is_status(ty)).cloned().collect();
			for (n, ty) in &outs {
				lines.push(self.out_decl(n, ty));
				call.args.push(format!("&o_{n}"));
			}
			if status {
				lines.push("::std::int32_t s_ = 0;".to_string());
				call.args.push("&s_".to_string());
			}
			let invoke = format!("::{c_name}({})", call.args.join(", "));
			match export.call.ret {
				Ty::Void => lines.push(format!("r::unlocked([&] {{ {invoke}; }});")),
				_ => lines.push(format!("auto r_ = r::unlocked([&] {{ return {invoke}; }});")),
			}
			if status {
				lines.push(format!("r::status(rt, s_, {});", lit(&c_name)));
			}
			lines.extend(std::mem::take(&mut call.writes));
			if handed {
				// A value's `&mut self`: the value as the call left it, before what it returns.
				let (_, owner_ty) = owner.expect("a method has its type");
				let this = self.lift(owner_ty, "self_", true);
				let returned: Vec<String> = match &function.ok {
					Type::Unit => Vec::new(),
					Type::Tuple(elements) => {
						let elems: Vec<&(String, Ty)> =
							outs.iter().filter(|(n, _)| !call.written.contains(n)).collect();
						(elements.iter().zip(elems))
							.map(|(e, (n, _))| self.lift(&strip_refs(e), &format!("o_{n}"), true))
							.collect()
					}
					ok => vec![self.lift(&strip_refs(ok), "r_", true)],
				};
				match returned.is_empty() {
					true => lines.push(format!("return {this};")),
					false => {
						let mut items = vec![this];
						items.extend(returned);
						lines.push(format!("jsi::Array out_(rt, {});", items.len()));
						for (n, item) in items.iter().enumerate() {
							lines.push(format!("out_.setValueAtIndex(rt, {n}, {item});"));
						}
						lines.push("return out_;".to_string());
					}
				}
			} else {
				match &err {
					Some(err) => {
						let value = match &ok {
							Type::Unit => "jsi::Value::undefined()".to_string(),
							_ => self.lift_outs(&function.ok, &ok),
						};
						let error = self.lift(err, "o_err", true);
						lines.push(format!(
							"if (r_) {{\n\treturn r::ok(rt, {value});\n}}\nreturn r::err(rt, {error});"
						));
					}
					None if ok == Type::Unit => lines.push("return jsi::Value::undefined();".to_string()),
					None if outs.len() > call.written.len() => {
						let value = self.lift_outs(&function.ok, &ok);
						lines.push(format!("return {value};"));
					}
					None => {
						let value = self.returned(&ok, "r_");
						lines.push(format!("return {value};"));
					}
				}
			}
		}
		let body: Vec<String> = lines.into_iter().filter(|l| !l.is_empty()).collect();
		self.host(&name, argc, &body.join("\n"));
	}

	/// The local the call writes the out `name` of C type `ty` to.
	fn out_decl(&self, name: &str, ty: &Ty) -> String {
		let Ty::Out(inner) = ty else {
			unreachable!("an out parameter is a pointer")
		};
		format!("{}{{}};", self.decl(inner, &format!("o_{name}")))
	}

	/// The value of a call's outs, which return `ok`, or each element of a tuple.
	fn lift_outs(&mut self, declared: &Type, ok: &Type) -> String {
		match declared {
			Type::Tuple(elements) => {
				let lifted: Vec<String> = (elements.iter().enumerate())
					.map(|(n, e)| self.lift(&strip_refs(e), &format!("o_out{n}"), true))
					.collect();
				format!("r::array(rt, {})", lifted.join(", "))
			}
			_ => self.returned(ok, "o_out"),
		}
	}

	/// The host functions of a type's std traits, each `<type>_<what>` as React Native's
	/// TypeScript forwards to.
	fn traits(&mut self, ty: &Type, c: &str, t: crate::ir::Traits, on: crate::ir::On) {
		let abi = self.abi;
		let c_ = crate::abi::stem(c).to_string();
		let bare = self.bare(&c_).to_string();
		let object = matches!(ty, Type::Object(_));
		let status = abi.traits_status_of(ty);
		let what = abi.spell(ty);
		// The statements lowering argument `k` as the receiver `local`.
		let this = |g: &mut Self, k: usize, local: &str| -> String {
			let v = format!("r::arg(a, n, {k})");
			match ty {
				Type::Object(i) => {
					let kind = g.kind(*i);
					format!("auto *{local} = static_cast<const {c} *>(f.hold({v}, {kind}));")
				}
				_ => {
					let decl = g.decl(&abi.ty(ty), local);
					format!("{decl}{{}};\n{}", g.lower(ty, &v, local, false))
				}
			}
		};
		let arg = |local: &str| match object {
			true => local.to_string(),
			false => format!("&{local}"),
		};
		let emit = |g: &mut Self, member: &str, receivers: usize, ret: &dyn Fn(&mut Self) -> String| {
			let mut lines = vec![g.lacks(on, &what), "r::frame f(rt);".to_string()];
			let mut args = Vec::new();
			for (k, local) in ["a_", "b_"].iter().take(receivers).enumerate() {
				lines.push(this(g, k, local));
				args.push(arg(local));
			}
			let has_status = status && member != "default";
			if has_status {
				lines.push("::std::int32_t s_ = 0;".to_string());
				args.push("&s_".to_string());
			}
			lines.push(format!(
				"auto r_ = r::unlocked([&] {{ return ::{c_}_{member}({}); }});",
				args.join(", ")
			));
			if has_status {
				lines.push(format!("r::status(rt, s_, {});", lit(&format!("{c_}_{member}"))));
			}
			lines.push(format!("return {};", ret(g)));
			let body: Vec<String> = lines.into_iter().filter(|l| !l.is_empty()).collect();
			g.host(&format!("{bare}_{member}"), receivers, &body.join("\n"));
		};
		if t.display {
			emit(self, "to_string", 1, &|_| "r::str(rt, r_, true)".to_string());
		}
		if t.debug {
			emit(self, "debug", 1, &|_| "r::str(rt, r_, true)".to_string());
		}
		if object && t.clone {
			emit(self, "clone", 1, &|g| g.lift(ty, "r_", true));
		}
		let plain = matches!(ty, Type::Enum(i) if abi.api.enums[*i].plain());
		if t.eq && !plain {
			emit(self, "eq", 2, &|_| "jsi::Value(static_cast<bool>(r_))".to_string());
			if t.hash {
				emit(self, "hash", 1, &|_| "r::of_u64(rt, r_)".to_string());
			}
		}
		for &(_, suffix) in crate::c::comparisons(t.ord) {
			emit(self, suffix, 2, &|_| "jsi::Value(static_cast<double>(r_))".to_string());
		}
		if t.default {
			emit(self, "default", 0, &|g| g.lift(ty, "r_", true));
		}
	}

	/// The trampoline of the closure type `ty`, which calls the JavaScript function its data
	/// holds.
	fn closure(&mut self, ty: &Type, closure: &Closure) -> String {
		if let Some(t) = self.closures.iter().position(|t| t == ty) {
			return format!("c{t}");
		}
		self.closures.push(ty.clone());
		let t = self.closures.len() - 1;
		let name = format!("c{t}");
		let abi = self.abi;
		let Ty::Fn(c_params, c_ret) = abi.closure(closure) else {
			unreachable!("a closure is a function")
		};
		let decls: Vec<String> = std::iter::once("void *data".to_string())
			.chain(
				c_params
					.iter()
					.enumerate()
					.map(|(n, ty)| self.decl(ty, &format!("p{n}"))),
			)
			.collect();
		let ret_c = self.decl(&c_ret, "");
		let mut lines = vec!["r::frame f(rt);".to_string()];
		let args: Vec<String> = (closure.params.iter().enumerate())
			.map(|(n, p)| self.incoming(p, &format!("p{n}")))
			.collect();
		lines.push(self.invoke_js("r::found(rt, data).asFunction(rt).call", &args));
		let back = match &closure.err {
			None => self.outgoing(&closure.ok, &c_ret, "v_"),
			Some(err) => {
				let at = closure.params.len();
				let err_at = c_params.len() - 1;
				let mut ok = String::new();
				if closure.ok != Type::Unit {
					ok = format!(
						"{}\n",
						self.lower(&closure.ok, "res_.getProperty(rt, \"value\")", &format!("*p{at}"), true)
					);
				}
				let error = self.lower(err, "res_.getProperty(rt, \"error\")", &format!("*p{err_at}"), true);
				format!(
					"jsi::Object res_ = r::obj(rt, v_, \"Result\");\nif (r::bool_(rt, res_.getProperty(rt, \"ok\"))) {{\n{}\n}}\n{error}\nreturn false;",
					indent(&format!("{ok}return true;"))
				)
			}
		};
		lines.push(back);
		let proto = format!("{ret_c} {name}({})", decls.join(", "));
		let body = self.trampoline(&c_ret, "a closure", &lines.join("\n"));
		self.define(&name, proto.clone(), format!("{proto} {{\n{}\n}}\n\n", indent(&body)));
		name
	}

	/// Statements calling the JavaScript function `callee`, as `callee(rt, args, n)`, into
	/// `v_`.
	fn invoke_js(&self, callee: &str, args: &[String]) -> String {
		match args.is_empty() {
			true => {
				format!("jsi::Value v_ = {callee}(rt, static_cast<const jsi::Value *>(nullptr), ::std::size_t{{0}});")
			}
			false => format!(
				"jsi::Value xs_[] = {{{}}};\njsi::Value v_ = {callee}(rt, static_cast<const jsi::Value *>(xs_), ::std::size_t{{{}}});",
				args.join(", "),
				args.len()
			),
		}
	}

	/// The body of a C function JavaScript implements, running `body` on the JavaScript
	/// thread for the value `data` holds.
	fn trampoline(&self, c_ret: &Ty, what: &str, body: &str) -> String {
		let (t, after) = match c_ret {
			Ty::Void => ("bool".to_string(), "\n\treturn true;"),
			ret => (self.decl(ret, ""), ""),
		};
		let call = format!(
			"r::out<{t}>(static_cast<r::remote *>(data)->w, {}, [&](jsi::Runtime &rt) -> {t} {{\n{}{after}\n}})",
			lit(what),
			indent(body)
		);
		match c_ret {
			Ty::Void => format!("(void){call};"),
			_ => format!("return {call};"),
		}
	}

	/// Statements returning `e` of type `ty` from a call into JavaScript, as the C type `c`,
	/// which Rust then owns.
	fn outgoing(&mut self, ty: &Type, c: &Ty, e: &str) -> String {
		if matches!(ty.base(), Type::Object(_)) {
			self.errors.push(format!(
				"`{}` returned from JavaScript to Rust has no React Native form yet, which rust2-ffi should give it",
				self.abi.spell(ty)
			));
			return String::new();
		}
		match c {
			Ty::Void => String::new(),
			c => format!(
				"{}{{}};\n{}\nreturn out_;",
				self.decl(c, "out_"),
				self.lower(ty, e, "out_", true)
			),
		}
	}

	/// The table of the trait `i`, whose methods JavaScript implements.
	fn vtable(&mut self, i: usize) -> String {
		let abi = self.abi;
		let c = abi.callback(i);
		let bare = self.bare(&c).to_string();
		let name = format!("vt_{bare}");
		if self.defs.contains_key(&name) {
			return name;
		}
		self.defs.insert(name.clone(), String::new());
		let callback = &abi.api.callbacks[i];
		let rust = callback.path.join("::");
		let mut fields = vec!["&r::trait_free".to_string()];
		for (k, (method, member)) in callback.methods.iter().zip(method_names(&callback.methods)).enumerate() {
			let m = format!("m_{bare}_{k}");
			let params: Vec<Ty> = method.params.iter().map(|p| abi.ty(&p.ty)).collect();
			let ret = abi.ty(&method.ok);
			let decls: Vec<String> = std::iter::once("void *data".to_string())
				.chain(params.iter().enumerate().map(|(n, ty)| self.decl(ty, &format!("p{n}"))))
				.collect();
			let mut lines = vec![
				"r::frame f(rt);".to_string(),
				"jsi::Object self_ = r::found(rt, data);".to_string(),
			];
			let args: Vec<String> = (method.params.iter().enumerate())
				.map(|(n, p)| self.incoming(&p.ty, &format!("p{n}")))
				.collect();
			let callee = format!("self_.getPropertyAsFunction(rt, {}).callWithThis", lit(&member));
			let call = self
				.invoke_js(&callee, &args)
				.replace("(rt, static_cast", "(rt, self_, static_cast");
			lines.push(call);
			lines.push(self.outgoing(&method.ok, &ret, "v_"));
			let proto = format!("{} {m}({})", self.decl(&ret, ""), decls.join(", "));
			let body = self.trampoline(&ret, &format!("{rust}::{}", method.name()), &lines.join("\n"));
			self.define(&m, proto.clone(), format!("{proto} {{\n{}\n}}\n\n", indent(&body)));
			fields.push(format!("&{m}"));
		}
		let vt = abi::join(&c, "vtable");
		self.defs.remove(&name);
		self.define(
			&name,
			format!("extern const {vt} {name}"),
			format!("const {vt} {name} = {{\n\t{},\n}};\n\n", fields.join(",\n\t")),
		);
		name
	}
}
